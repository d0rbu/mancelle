"""O1 (issue #531): parallel shard compress+save via a bounded thread pool. The output MUST be
byte-identical across worker counts (the producer's packing is strictly serial; only the pure
per-shard assemble+compress runs off-thread, each writing its own file), a worker exception MUST
abort loudly, and the bounded semaphore MUST cap in-flight shards."""
from __future__ import annotations

import threading
import time

import pytest
import torch as t

import scripts.preprocess.precompute_packed_rows as m
from scripts.preprocess.precompute_packed_rows import precompute_packed_rows
from steering.gradient_overlay import provenance_dir
from steering.packed_batch_io import load_packed_row_shard
from tests.scripts._packed_rows_fixtures import (
    GOLDEN_SEED,
    SimpleTokenizer,
    _copy_shards,
    _make_feature_index,
    _make_precompute_env,
    _shard_bytes,
)


def _run(env, out, *, compress_workers):
    out.mkdir(parents=True, exist_ok=True)
    precompute_packed_rows(
        parquet_paths=env["parquet_paths"],
        tokenizer=SimpleTokenizer(),
        feature_index=_make_feature_index(env),
        context_len=32,
        output_dir=out,
        buffer_size=20,
        rows_per_shard=3,
        compress_workers=compress_workers,
    )
    return _shard_bytes(out)


def _boom_after(real, n: int, msg: str):
    """Wrap `real` so its n-th call raises RuntimeError(msg) (issue #540: shared by the worker- and
    producer-exception tests instead of re-implementing the boom/counter closure each time)."""
    state = {"calls": 0}

    def wrapper(*args, **kwargs):
        state["calls"] += 1
        if state["calls"] == n:
            raise RuntimeError(msg)
        return real(*args, **kwargs)

    return wrapper


@pytest.mark.parametrize("workers", [1, 4, 16])
def test_parallel_byte_identical_across_worker_counts(tmp_path, workers):
    t.manual_seed(GOLDEN_SEED)
    env = _make_precompute_env(tmp_path, n_shards=4)
    ref = _run(env, tmp_path / "ref", compress_workers=1)
    assert len(ref) >= 4, "need several output shards to exercise parallelism"
    cur = _run(env, tmp_path / f"w{workers}", compress_workers=workers)
    assert cur == ref


def test_worker_exception_aborts_loudly(tmp_path, monkeypatch):
    env = _make_precompute_env(tmp_path, n_shards=4)
    monkeypatch.setattr(m, "_assemble_and_save", _boom_after(m._assemble_and_save, 1, "disk full"))
    with pytest.raises(RuntimeError, match="disk full"):
        _run(env, tmp_path / "boom", compress_workers=4)


def test_resume_fills_gap_from_parallel_crash(tmp_path):
    """O1's parallel compress finishes shards out of order, so a crash can leave a NON-contiguous
    shard set on disk. resume=true must count the contiguous shard_00000..N-1 prefix (not
    len(glob)), so it re-packs from the first missing shard, fills the gap, and stays
    byte-identical to an uninterrupted run. The old len(glob) logic would over-count and skip the
    wrong number of rows, permanently leaving the gap."""
    env = _make_precompute_env(tmp_path, n_shards=4)
    full = tmp_path / "full"
    full.mkdir()
    precompute_packed_rows(
        parquet_paths=env["parquet_paths"], tokenizer=SimpleTokenizer(),
        feature_index=_make_feature_index(env), context_len=32, output_dir=full,
        buffer_size=20, rows_per_shard=3, compress_workers=4,
    )
    full_bytes = _shard_bytes(full)
    assert len(full_bytes) >= 5, "need >=5 shards for a meaningful middle gap"

    # Simulate a parallel-crash: copy every COMPLETE shard (packed + provenance +
    # _dims) EXCEPT a middle one (a gap an out-of-order pool can leave). 0,1 are
    # the contiguous prefix; 2 is the gap; 3.. exist past the gap. Provenance must
    # ride along, else resume sees the prefix as incomplete and re-packs from 0.
    gap_idx = 2
    gap_dir = tmp_path / "gap"
    kept = [
        i for i in (int(n.split("_")[1].split(".")[0]) for n in full_bytes)
        if i != gap_idx
    ]
    _copy_shards(full, gap_dir, kept)

    precompute_packed_rows(
        parquet_paths=env["parquet_paths"], tokenizer=SimpleTokenizer(),
        feature_index=_make_feature_index(env), context_len=32, output_dir=gap_dir,
        buffer_size=20, rows_per_shard=3, resume=True, compress_workers=4,
    )
    assert _shard_bytes(gap_dir) == full_bytes
    # The gap shard's provenance was NOT copied (only its packed neighbors'),
    # so resume must HEAL it via the normal flush. Validate the provenance was
    # regenerated byte-identically across the WHOLE dir (the re-packed gap +
    # the byte-identically-rewritten tail), not just that the packed rows match.
    assert _shard_bytes(provenance_dir(gap_dir)) == _shard_bytes(provenance_dir(full))


def test_global_max_dims_equal_true_max_and_stable_across_workers(tmp_path):
    """The futures-join loop reduces each shard's (max_n_seg, max_seg_size) into the returned
    global maxima (issue #531 F-A1/B-A1), which run() writes as the manifest's static-padding
    metadata (consumed by the encoder-decoder dataloader for fixed-shape allocation). Pin that on a
    real run the reduction equals the TRUE max over ALL written shards and is IDENTICAL across
    compress_workers (order-independent). The byte-identity suite can't catch a reduction bug: it
    compares only `_shard_bytes`, and `_run` discards the returned maxima entirely."""
    t.manual_seed(GOLDEN_SEED)
    env = _make_precompute_env(tmp_path, n_shards=4)

    def run_and_reduce(workers, name):
        out = tmp_path / name
        out.mkdir()
        total_rows, gmax_nseg, gmax_sseg = precompute_packed_rows(
            parquet_paths=env["parquet_paths"], tokenizer=SimpleTokenizer(),
            feature_index=_make_feature_index(env), context_len=32, output_dir=out,
            buffer_size=20, rows_per_shard=3, compress_workers=workers,
        )
        per_shard = [
            m._compute_shard_max_dims(load_packed_row_shard(p))
            for p in sorted(out.glob("shard_*.safetensors.zst"))
        ]
        assert len(per_shard) >= 3
        return (total_rows, gmax_nseg, gmax_sseg), (
            max(n for n, _ in per_shard), max(s for _, s in per_shard),
        )

    base, true_dims = run_and_reduce(1, "w1")
    total_rows, gmax_nseg, gmax_sseg = base
    assert total_rows > 0 and gmax_nseg > 0 and gmax_sseg > 0
    assert (gmax_nseg, gmax_sseg) == true_dims, "reduction != true max over written shards"
    for w in (4, 16):
        cur, _ = run_and_reduce(w, f"w{w}")
        assert cur == base, f"global max dims diverged at compress_workers={w}: {cur} != {base}"


def test_global_max_reduction_takes_max_not_last_shard(tmp_path, monkeypatch):
    """Reduction teeth (issue #531 F-A1): the futures-join must take the MAX over per-shard dims,
    not the last-joined shard's. Force the global max into shard 0 (a non-final shard) and assert
    the returned maxima surface it — a `global_max_n_seg = shard_mns` 'last wins' regression would
    instead yield the final shard's small dims. Env-shape-independent (overriding only the RETURNED
    dims, not the written bytes), so it catches the bug regardless of which shard naturally holds
    the corpus max."""
    env = _make_precompute_env(tmp_path, n_shards=4)
    real = m._assemble_and_save

    def force_max_in_shard0(
        shard_idx, shard_rows, shard_prov, out_path, prov_path, zstd_level, dims_path
    ):
        # Write the real shard (bytes unchanged), but report a large max ONLY for shard 0.
        idx, _n, _s, timing = real(
            shard_idx, shard_rows, shard_prov, out_path, prov_path, zstd_level, dims_path
        )
        return idx, (100 if idx == 0 else 3), (50 if idx == 0 else 3), timing

    monkeypatch.setattr(m, "_assemble_and_save", force_max_in_shard0)
    out = tmp_path / "forced"
    out.mkdir()
    _rows, gmax_nseg, gmax_seg = precompute_packed_rows(
        parquet_paths=env["parquet_paths"], tokenizer=SimpleTokenizer(),
        feature_index=_make_feature_index(env), context_len=32, output_dir=out,
        buffer_size=20, rows_per_shard=3, compress_workers=4,
    )
    assert len(sorted(out.glob("shard_*.safetensors.zst"))) >= 2, "need shard 0 to be non-final"
    assert (gmax_nseg, gmax_seg) == (100, 50), (
        f"reduction returned {(gmax_nseg, gmax_seg)}, not shard 0's max (100, 50): a 'last shard "
        f"wins' reduction (global = shard_mns) would yield the final shard's (3, 3)"
    )


def test_backpressure_bounds_inflight_shards(tmp_path, monkeypatch):
    """The bounded semaphore caps concurrently-executing compress tasks at compress_workers."""
    env = _make_precompute_env(tmp_path, n_shards=4)
    real = m._assemble_and_save
    workers = 2
    lock = threading.Lock()
    state = {"cur": 0, "max": 0}

    def tracked(*args, **kwargs):
        with lock:
            state["cur"] += 1
            state["max"] = max(state["max"], state["cur"])
        try:
            time.sleep(0.02)  # hold the slot so the producer races ahead into the semaphore
            return real(*args, **kwargs)
        finally:
            with lock:
                state["cur"] -= 1

    monkeypatch.setattr(m, "_assemble_and_save", tracked)
    out = _run(env, tmp_path / "bp", compress_workers=workers)
    assert len(out) >= 4
    assert state["max"] <= workers, f"observed {state['max']} concurrent > {workers}"
    assert state["max"] >= 1


def test_producer_exception_aborts_loudly_through_pool(tmp_path, monkeypatch):
    """A non-StopIteration producer-side exception (e.g. a corrupt-shard lookup, issue #521) must
    propagate out of precompute_packed_rows and NOT deadlock the live compress pool: the
    try/finally pool.shutdown() drains in-flight workers and the run aborts loudly (issue #540 A1).
    Run on a watchdog thread so a future deadlock regression fails fast (join timeout) instead of
    hanging the suite forever."""
    env = _make_precompute_env(tmp_path, n_shards=4)
    # Raise on the 5th _row_to_csr (> rows_per_shard=3, so shard 0 has flushed + is in flight).
    monkeypatch.setattr(m, "_row_to_csr", _boom_after(m._row_to_csr, 5, "producer boom"))
    out = tmp_path / "boom"
    out.mkdir()
    caught = {}

    def run_it():
        try:
            precompute_packed_rows(
                parquet_paths=env["parquet_paths"], tokenizer=SimpleTokenizer(),
                feature_index=_make_feature_index(env), context_len=32, output_dir=out,
                buffer_size=20, rows_per_shard=3, compress_workers=4,
            )
        except BaseException as exc:  # capture so the parent can assert loud propagation
            caught["exc"] = exc

    th = threading.Thread(target=run_it)
    th.start()
    th.join(timeout=30)
    assert not th.is_alive(), "run hung — the producer exception did not abort the pool (deadlock?)"
    exc = caught.get("exc")
    assert isinstance(exc, RuntimeError) and "producer boom" in str(exc), (
        f"expected the producer RuntimeError to propagate, got {exc!r}"
    )


def test_backpressure_bounds_submitted_inflight_not_just_execution(tmp_path, monkeypatch):
    """The bounded semaphore caps SUBMITTED-but-incomplete shards (peak memory) — distinct from
    ThreadPoolExecutor's execution cap, which would let the producer queue EVERY shard. Stall
    completion and track in-flight = submitted - done via an instrumented pool; the producer blocks
    once `workers` are in flight, so peak in-flight == workers EXACTLY (issue #540 N1). Teeth: drop
    the semaphore and the producer submits all shards -> peak > workers; over-throttle (cap at 1)
    -> peak < workers; both fail the `== workers` check."""
    env = _make_precompute_env(tmp_path, n_shards=4)
    workers = 2
    lock = threading.Lock()
    state = {"inflight": 0, "max_inflight": 0}
    filled = threading.Event()   # set once peak first reaches `workers`
    gate = threading.Event()     # release the stalled workers
    real_pool_cls = m.ThreadPoolExecutor

    def dec(_f):
        with lock:
            state["inflight"] -= 1

    class TrackingPool(real_pool_cls):
        def submit(self, fn, /, *args, **kwargs):
            def stalled(*a, **k):
                gate.wait(timeout=15)  # hold completion so submissions would pile up w/o the semaphore
                return fn(*a, **k)
            with lock:
                state["inflight"] += 1
                state["max_inflight"] = max(state["max_inflight"], state["inflight"])
                reached = state["max_inflight"] >= workers
            if reached:
                filled.set()
            fut = super().submit(stalled, *args, **kwargs)
            fut.add_done_callback(dec)
            return fut

    monkeypatch.setattr(m, "ThreadPoolExecutor", TrackingPool)
    out = tmp_path / "bp2"
    out.mkdir()
    caught = {}

    def run_it():
        try:
            precompute_packed_rows(
                parquet_paths=env["parquet_paths"], tokenizer=SimpleTokenizer(),
                feature_index=_make_feature_index(env), context_len=32, output_dir=out,
                buffer_size=20, rows_per_shard=3, compress_workers=workers,
            )
        except BaseException as exc:  # surface a producer-side crash so the green isn't a mask
            caught["exc"] = exc

    th = threading.Thread(target=run_it)
    th.start()
    # Deterministically wait until the producer has filled the semaphore to `workers` (no fixed
    # sleep race), then a brief settle during which an UNBOUNDED producer would over-submit.
    assert filled.wait(timeout=20), "producer never reached `workers` in-flight shards"
    time.sleep(0.1)  # with the semaphore the producer is now blocked, so peak stays == workers
    with lock:
        peak = state["max_inflight"]
    gate.set()  # release the stalled workers so the run can complete
    th.join(timeout=30)
    assert not th.is_alive(), "run hung (deadlock?)"
    assert "exc" not in caught, f"run raised mid-flight: {caught.get('exc')!r}"
    assert peak == workers, (
        f"peak in-flight {peak} != workers {workers}: the semaphore must bound submitted-but-"
        f"incomplete shards to exactly compress_workers (peak > workers => no/under-throttle; "
        f"peak < workers => over-throttle)"
    )
    assert len(_shard_bytes(out)) >= 4
