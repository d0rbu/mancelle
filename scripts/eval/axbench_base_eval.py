#: Stages that are rank-aware under DDP (multi-GPU). Every other stage
#: is rank-0-only when ``world_size > 1``.
_RANK_AWARE_STAGES: frozenset[Stage] = frozenset(
    {Stage.PREPARE_SEED_POOLS, Stage.PREPARE_NEGATIVE_PREFIXES}
)


def _stage_runs_on_rank(stage: Stage, *, rank: int) -> bool:
    """Return ``True`` iff this rank should execute ``stage``.

    Stages 0b and 0c execute collectively. All other stages are rank-0-only
    under DDP; non-rank-0 ranks barrier and skip.
    """
    return stage in _RANK_AWARE_STAGES or rank == 0


def _maybe_barrier(world_size: int) -> None:
    """Block until all ranks reach this point. No-op for single-rank runs.

    Required between stages whose execution is gated to rank 0 only:
    rank 0 must finish writing shared state before any later stage on
    other ranks reads it. Mirrors the ``_maybe_barrier`` helper in
    :mod:`scripts.eval.axbench_bpb_eval`.
    """
    if world_size <= 1:
        return
    if not (dist.is_available() and dist.is_initialized()):
        return
    dist.barrier()


def _assert_ddp_output_root_agreement(
    cfg: AxBenchBaseConfig,
    *,
    world_size: int,
) -> None:
    """Fail collectively when ranks resolve different output parents.

    Hydra environment interpolation is evaluated independently in each
    process. A rank-dependent ``output_root`` would therefore split collective
    stages across artifact trees and eventually deadlock. Compare both the
    configured identity and the effective absolute location before any stage
    can write.
    """
    if world_size <= 1 or not (dist.is_available() and dist.is_initialized()):
        return
    try:
        effective_root = paths.effective_output_root(cfg.output_root)
        local_identity: dict[str, object] = {
            "configured_output_root": cfg.output_root,
            "effective_output_root": str(effective_root),
            "resolved_output_root": str(effective_root.resolve(strict=False)),
            "error": None,
        }
    except Exception as exc:
        local_identity = {
            "configured_output_root": cfg.output_root,
            "effective_output_root": None,
            "resolved_output_root": None,
            "error": f"{type(exc).__name__}: {exc}",
        }
    gathered: list[dict[str, object] | None] = [None] * world_size
    dist.all_gather_object(gathered, local_identity)
    if any(identity is None or identity.get("error") is not None for identity in gathered):
        raise AxBenchBaseError(
            "One or more AxBench-Base DDP ranks could not resolve output_root. "
            f"Per-rank identities: {gathered}"
        )
    if any(identity != gathered[0] for identity in gathered[1:]):
        raise AxBenchBaseError(
            "AxBench-Base DDP ranks resolved different output roots; all ranks "
            f"must share one configured and effective output_root. Per-rank "
            f"identities: {gathered}"
        )


def _synchronize_ddp_run_tag(
    cfg: AxBenchBaseConfig,
    *,
    rank: int,
    world_size: int,
    generated: bool,
) -> AxBenchBaseConfig:
    """Broadcast an autogenerated tag or require exact explicit-tag parity."""
    if world_size <= 1 or not (dist.is_available() and dist.is_initialized()):
        return cfg
    if generated:
        payload = [cfg.run_tag if rank == 0 else None]
        dist.broadcast_object_list(payload, src=0)
        rank0_tag = payload[0]
        if not isinstance(rank0_tag, str) or not rank0_tag:
            raise AxBenchBaseError(
                f"AxBench-Base rank 0 broadcast invalid autogenerated run_tag "
                f"{rank0_tag!r}"
            )
        return cfg.replace(run_tag=rank0_tag)

    gathered: list[str | None] = [None] * world_size
    dist.all_gather_object(gathered, cfg.run_tag)
    if any(run_tag != gathered[0] for run_tag in gathered[1:]):
        raise AxBenchBaseError(
            "AxBench-Base DDP ranks received different explicit run_tag values; "
            f"all ranks must address one run. Per-rank values: {gathered}"
        )
    return cfg


def _assert_no_legacy_output_shadow_ddp(
    cfg: AxBenchBaseConfig,
    *,
    rank: int,
    world_size: int,
) -> None:
    """Let rank 0 decide the filesystem migration preflight for all ranks."""
    error: str | None = None
    if rank == 0:
        try:
            paths.assert_no_legacy_output_shadow(cfg)
        except AxBenchBaseError as exc:
            error = str(exc)
        except Exception as exc:
            error = (
                "AxBench-Base legacy-output shadow preflight failed on rank 0: "
                f"{type(exc).__name__}: {exc}"
            )
    _broadcast_resume_decision(
        None,
        rank=rank,
        world_size=world_size,
        resume_error=error,
    )


def _broadcast_rank0_stage_outcome(
    stage: Stage,
    *,
    rank: int,
    world_size: int,
    failure: Exception | None,
) -> None:
    """Broadcast rank 0's rank-only stage result and raise it on every rank."""

    _broadcast_resume_decision(
        None,
        rank=rank,
        world_size=world_size,
        resume_error=(
            f"Rank-0-only stage {stage.value!r} failed collectively: "
            f"{type(failure).__name__}: {failure}"
            if failure is not None
            else None
        ),
    )


def _device_type_from_cfg(device: str) -> str:
    """Extract the bare device type from ``cfg.device``.

    :func:`nanochat.common.compute_init` requires one of
    ``"cuda" | "cpu" | "mps"`` (the :class:`DeviceType` StrEnum). This
    helper strips a trailing ``":<index>"`` from values like
    ``"cuda:0"`` so callers can pass the raw cfg value through.
    """
    head = str(device).split(":", 1)[0].strip().lower()
    if head not in ("cuda", "cpu", "mps"):
        raise AxBenchBaseError(
            f"Unsupported cfg.device {device!r}: expected 'cuda', 'cuda:N', "
            "'cpu', or 'mps'."
        )
    return head


_LEGACY_DEFAULT_OUTPUT_ROOT_IDENTITY = "out/eval/axbench_base"


def _run_tag_config_to_dict(cfg: AxBenchBaseConfig) -> dict[str, Any]:
    """Serialize config identity while preserving the historical default tag.

    ``output_root`` used to default to the literal string below even though
    artifacts ignored it. The corrected configuration uses ``null`` to mean
    the actual historical artifact root. Normalizing only this disabled/default
    value preserves every existing default run-tag suffix; explicit custom
    roots retain their literal identity.
    """
    payload = axbench_base_config_to_dict(cfg)
    if cfg.output_root is None:
        payload["output_root"] = _LEGACY_DEFAULT_OUTPUT_ROOT_IDENTITY
    return payload


def _generate_run_tag(cfg: AxBenchBaseConfig) -> str:
    """Build a deterministic ``run_tag`` from the current UTC second + a
    short hash over the serialized config.

    Format::

        YYYYMMDD-HHMMSS-<8-char-hex>

    The hash is the first 8 hex characters of
    ``sha256(json.dumps(_run_tag_config_to_dict(cfg), sort_keys=True))``.
    The serializer preserves both the null ``output_root`` default's historical
    identity and the existing null ``conditioning.feature_clusters`` omission,
    while retaining real custom values.
    The safe cryptographic hash is truncated to 32 bits since we only need
    collision resistance at the scale of "same operator starting two runs in
    the same second".

    Two calls with the same config content starting in the same UTC
    second produce the same tag; calls whose configs differ in their
    *serialized identity* produce different tags (different hash suffix).
    Calls across second boundaries produce different tags.

    Note the qualifier: identity is the serialized form, not raw field
    equality. A ``conditioning`` mapping carrying an explicit
    ``feature_clusters: None`` and one omitting the key entirely are
    different config values that deliberately share a tag, because the
    serializer drops the disabled key. That is the whole point of routing
    through ``_run_tag_config_to_dict`` -- it is what lets disabled defaults be
    represented accurately without silently re-tagging pre-existing runs.
    """
    now = _DateTime.now(tz=UTC)
    timestamp = now.strftime("%Y%m%d-%H%M%S")
    cfg_bytes = json.dumps(_run_tag_config_to_dict(cfg), sort_keys=True).encode("utf-8")
    digest = hashlib.sha256(cfg_bytes).hexdigest()[:8]
    return f"{timestamp}-{digest}"


def _cluster_contract_request(
    cfg: AxBenchBaseConfig,
) -> ClusterFeatureContractRequest | None:
    """Build the path-only clustered preflight request without writing output."""

    conditioning = cfg.conditioning
    if not isinstance(conditioning, Mapping) or (
        conditioning.get("feature_clusters") is None
    ):
        return None
    feature_mask = conditioning.get("feature_mask")
    feature_clusters = conditioning.get("feature_clusters")
    if not isinstance(feature_mask, Mapping) or not isinstance(
        feature_clusters, Mapping
    ):
        raise AxBenchBaseError(
            "clustered conditioning requires feature_mask and feature_clusters "
            "mappings"
        )
    encdec = cfg.encdec
    source = encdec.get("source")
    model_tag = encdec.get("model_tag")
    if not isinstance(source, str) or not source:
        raise AxBenchBaseError("clustered encdec.source must be a non-empty string")
    if not isinstance(model_tag, str) or not model_tag:
        raise AxBenchBaseError(
            "clustered encdec.model_tag must be a non-empty string"
        )
    raw_step = encdec.get("step")
    if raw_step in (None, "last"):
        step = None
    elif isinstance(raw_step, Integral) and not isinstance(raw_step, bool):
        step = int(raw_step)
    else:
        raise AxBenchBaseError(
            "clustered encdec.step must be a non-negative integer, null, or "
            f"'last'; got {raw_step!r}"
        )
    if step is not None and step < 0:
        raise AxBenchBaseError("clustered encdec.step must be non-negative")
    return ClusterFeatureContractRequest(
        feature_dir=cfg.feature_dir,
        feature_statistics_path=cfg.feature_statistics_path,
        feature_mask=feature_mask,
        feature_clusters=feature_clusters,
        checkpoint_source=source,
        checkpoint_model_tag=model_tag,
        checkpoint_step=step,
        checkpoint_tag=model_tag,
        concept_feature_whitelist_path=cfg.concept_feature_whitelist_path,
        # Both are contract inputs the checkpoint cannot supply itself:
        # `selection_splice_batch_size` is producer-side provenance that
        # participates in the selection hash, and `enabled_methods` is required
        # whenever the checkpoint carries an auxiliary feature-prediction head.
        selection_splice_batch_size=cfg.selection_splice_batch_size,
        # Explicit disambiguation for a feature root that legitimately holds
        # several packed-row splits (train / val / val-subset) sharing one
        # selection hash. Discovery refuses to guess between them, and their
        # manifests are semantically distinct, so the caller names one.
        selection_manifest_path=cfg.selection_manifest_path,
        enabled_methods=(
            None if cfg.enabled_methods is None else tuple(cfg.enabled_methods)
        ),
        force_cluster_shard_revalidation=cfg.force_cluster_shard_revalidation,
    )


