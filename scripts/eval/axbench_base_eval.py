def _resolve_stage_list(
    stage: Stage | str, run_negative_mode: bool,
) -> list[Stage]:
    """Expand ``stage`` into the explicit ordered list of stages to run.

    - :attr:`Stage.ALL` (or ``"all"``) → every stage in
      :data:`_ALL_STAGES_IN_ORDER`, dropping
      :attr:`Stage.SYNTH_NEGATIVE_MODE` when ``run_negative_mode`` is
      ``False``.
    - A single :class:`Stage` member or its string form
      (e.g. ``Stage.PREPARE_CONCEPTS`` or ``"0a"``) → a one-element
      list containing that stage. No neg-mode filtering is applied
      for explicit single-stage requests; the dep check + runtime
      can short-circuit as needed.
    - Unknown name → :class:`AxBenchBaseError`.
    """
    stage_enum = Stage.coerce(stage)
    if stage_enum is Stage.ALL:
        if run_negative_mode:
            return list(_ALL_STAGES_IN_ORDER)
        return [s for s in _ALL_STAGES_IN_ORDER if s is not Stage.SYNTH_NEGATIVE_MODE]
    return [stage_enum]


