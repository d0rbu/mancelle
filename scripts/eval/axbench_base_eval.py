def _run_scalar_baseline_training(
    cfg: AxBenchBaseConfig,
    state: RuntimeState,
    *,
    trainer: Callable[..., list[Path]],
    targets: tuple[str, ...],
) -> None:
    """Execute a scalar-baseline trainer across targets x modes.

    All three scalar-baseline trainers (``train_diffmean_all``,
    ``train_linear_probe_all``, ``train_lora_all``) share an identical
    six-argument signature::

        trainer(
            cfg,
            target_model=<module>,
            target_model_name="decoder_only" | "encdec",
            mode=SteeringMode.POSITIVE | SteeringMode.NEGATIVE,
            concepts=<list>,
            training_corpus_path=<Path>,
        )

    This helper extracts the common dispatch pattern shared by
    :attr:`Stage.TRAIN_DIFFMEAN`, :attr:`Stage.TRAIN_LINEAR_PROBE`, and
    :attr:`Stage.TRAIN_LORA`: enter each target model context in turn,
    loop modes (positive + optionally negative), resolve the training
    corpus path per mode, and invoke ``trainer``. The caller supplies
    ``targets`` so Stage 3d (LoRA, decoder-only only) can pass
    ``("decoder_only",)`` instead of the usual
    ``("decoder_only", "encdec")`` for the other two stages.
    """
    modes: list[SteeringMode] = [SteeringMode.POSITIVE]
    if cfg.run_negative_mode:
        modes.append(SteeringMode.NEGATIVE)
    for target_name in targets:
        if target_name not in {"decoder_only", "encdec"}:
            raise AxBenchBaseError(
                f"Unknown target name {target_name!r} in scalar baseline "
                f"training helper. Expected 'decoder_only' or 'encdec'."
            )
    if not targets:
        return

    output_paths = state.output_paths()
    concepts = state.downstream_concepts()
    for mode in modes:
        require_complete_concept_population_from_corpus(
            output_paths.synth_training(mode),
            (concept.concept_id for concept in concepts),
            mode=mode,
            consumer="Stage 3 scalar-baseline training",
            positive_accept_threshold=(
                cfg.accept_threshold
                if mode is SteeringMode.POSITIVE
                else None
            ),
        )
    for target_name in targets:
        # #1249: encdec-target directions are fit under the concept's committed
        # fair feature-DiffMean bag -- the SAME artifact the eval pipeline
        # steers with. Loaded BEFORE the model context so a missing/invalid bag
        # store fails in milliseconds, not after a checkpoint load; the bags are
        # tiny CPU-side safetensors, so nothing heavy is resident yet.
        encdec_conditioning_by_mode: dict[SteeringMode, dict[int, Any]] = {}
        if target_name == "encdec":
            if cfg.encdec_fit_bag_store is None:
                raise AxBenchBaseError(
                    "stage 3a/3b trains the encdec target, which requires "
                    "cfg.encdec_fit_bag_store (an adv run's ours_gcg_bags "
                    "directory holding the committed fair feature-DiffMean "
                    "bags). Fitting encdec directions under an unconditioned "
                    "forward was removed in #1249 and has no fallback."
                )
            for mode in modes:
                encdec_conditioning_by_mode[mode] = load_encdec_fit_conditioning(
                    cfg.encdec_fit_bag_store,
                    mode=mode,
                    concept_ids=[c.concept_id for c in concepts],
                    expected_feature_contract_fingerprint=(
                        None
                        if state.cluster_contract is None
                        else state.cluster_contract.feature_contract_fingerprint
                    ),
                )
        if target_name == "decoder_only":
            model_cm = state.decoder_only_model()
        else:
            model_cm = state.encdec_model()
        with model_cm as target_model:
            for mode in modes:
                corpus_path = output_paths.synth_training(mode)
                trainer(
                    cfg,
                    target_model=target_model,
                    target_model_name=target_name,
                    mode=mode,
                    concepts=concepts,
                    training_corpus_path=corpus_path,
                    **(
                        {}
                        if target_name != "encdec"
                        else {
                            "encoder_conditioning_for": (
                                encdec_conditioning_by_mode[mode].__getitem__
                            )
                        }
                    ),
                    **(
                        {}
                        if state.cluster_contract is None
                        else {
                            "feature_contract_fingerprint": (
                                state.cluster_contract.feature_contract_fingerprint
                            )
                        }
                    ),
                )


def _encdec_model_sequence_len(encdec_model: object) -> int:
    """Return the encoder-decoder decoder sequence length or raise clearly."""
    dec_config = getattr(encdec_model, "dec_config", None)
    if dec_config is None:
        dec_config = getattr(encdec_model, "config", None)
    raw_sequence_len = getattr(dec_config, "sequence_len", None)
    if not isinstance(raw_sequence_len, Integral) or isinstance(
        raw_sequence_len, bool,
    ):
        raise AxBenchBaseError(
            "AxBench-Base Stage 4 encoder-decoder generation requires "
            "encdec_model.dec_config.sequence_len to build the full-context "
            f"cache provider; got {raw_sequence_len!r}."
        )
    sequence_len = int(raw_sequence_len)
    if sequence_len <= 0:
        raise AxBenchBaseError(
            "AxBench-Base Stage 4 encoder-decoder generation requires a "
            "positive encdec_model.dec_config.sequence_len; got "
            f"{sequence_len}."
        )
    return sequence_len


def _fill_or_check_conditioning_int(
    cond: dict[str, object],
    *,
    field_name: str,
    meta_value: int | None,
) -> None:
    """Fill a missing conditioning int from metadata and reject mismatches."""
    raw_value = cond.get(field_name)
    if raw_value is None:
        if meta_value is None:
            raise AxBenchBaseError(
                f"conditioning.{field_name} is required for AxBench-Base "
                "Stage 4 encoder-decoder generation because the target "
                f"metadata did not provide {field_name}."
            )
        cond[field_name] = int(meta_value)
        return
    if isinstance(raw_value, bool):
        raise AxBenchBaseError(
            f"conditioning.{field_name} must be an integer, got "
            f"{raw_value!r}."
        )
    if isinstance(raw_value, Integral):
        cfg_value = int(raw_value)
    elif isinstance(raw_value, str):
        try:
            cfg_value = int(raw_value)
        except ValueError as exc:
            raise AxBenchBaseError(
                f"conditioning.{field_name} must be an integer, got "
                f"{raw_value!r}."
            ) from exc
    else:
        raise AxBenchBaseError(
            f"conditioning.{field_name} must be an integer, got "
            f"{raw_value!r}."
        )
    if cfg_value <= 0:
        raise AxBenchBaseError(
            f"conditioning.{field_name} must be positive, got {cfg_value}."
        )
    if meta_value is not None and cfg_value != int(meta_value):
        raise AxBenchBaseError(
            f"conditioning.{field_name}={cfg_value} does not match the "
            f"encoder-decoder checkpoint metadata value {int(meta_value)}. "
            "The context cache must match the model that consumes it."
        )
    cond[field_name] = cfg_value


def _build_stage4_encdec_context_provider(
    cfg: AxBenchBaseConfig,
    *,
    encdec_model: object,
    encdec_meta: TargetModelMetadata,
    cluster_contract: ClusterFeatureContract | None = None,
) -> ContextProvider:
    """Build the cache-backed full-context provider required by Stage 4 encdec."""
    if cfg.conditioning is None:
        raise AxBenchBaseError(
            "AxBench-Base Stage 4 encoder-decoder generation requires a "
            "conditioning block with conditioning.context_cache_dir. Build a "
            "context cache for the exact Stage 4 seed-prefix token sequences "
            "and pass its root via conditioning.context_cache_dir."
        )
    if not isinstance(cfg.conditioning, dict):
        raise AxBenchBaseError(
            "AxBench-Base Stage 4 conditioning must be a mapping, got "
            f"{type(cfg.conditioning).__name__}."
        )
    cache_root = cfg.conditioning.get("context_cache_dir")
    if cache_root is None or str(cache_root) == "":
        raise AxBenchBaseError(
            "AxBench-Base Stage 4 encoder-decoder generation requires "
            "conditioning.context_cache_dir so seed prefixes receive real "
            "prompt/context SAE features."
        )

    cond: dict[str, object] = dict(cfg.conditioning)
    _fill_or_check_conditioning_int(
        cond,
        field_name="n_sae_features",
        meta_value=encdec_meta.n_sae_features,
    )
    _fill_or_check_conditioning_int(
        cond,
        field_name="num_buckets",
        meta_value=encdec_meta.num_buckets,
    )
    model_max_seq_len = _encdec_model_sequence_len(encdec_model)
    assert cfg.run_tag is not None
    contexts_manifest = load_stage4_contexts_manifest(
        paths.AxBenchBasePaths.from_config(cfg).stage4_contexts_manifest()
    )
    if int(contexts_manifest.get("encdec_sequence_len", -1)) != model_max_seq_len:
        raise AxBenchBaseError(
            "Stage 3e contexts were enumerated for a different encoder-decoder "
            "sequence length; rerun Stage 3e and rebuild the context cache"
        )
    expected_metadata = {"contexts_fingerprint": contexts_manifest["contexts_fingerprint"]}
    if cluster_contract is not None:
        if contexts_manifest.get("feature_contract_fingerprint") != (
            cluster_contract.feature_contract_fingerprint
        ):
            raise AxBenchBaseError("Stage 3e contexts do not match the loaded clustered checkpoint")
        expected_metadata.update(clustered_context_cache_metadata_for_contract(cluster_contract))
    elif contexts_manifest.get("feature_contract_fingerprint") is not None:
        raise AxBenchBaseError("Unclustered Stage 4 rejects cluster-stamped Stage 3e contexts")
    provider_cfg = OmegaConf.create(
        {
            "conditioning": cond,
            "model_max_seq_len": model_max_seq_len,
        }
    )
    try:
        return build_context_feature_provider(
            provider_cfg,
            cache_dir=cache_root,
            error_prefix="conditioning.context_cache_dir",
            expected_metadata=expected_metadata,
        )
    except Exception as exc:
        raise AxBenchBaseError(
            "Failed to build the AxBench-Base Stage 4 encoder-decoder "
            "full-context provider from conditioning.context_cache_dir. "
            "The cache identity, n_sae_features, num_buckets, and "
            "model_max_seq_len must match the encoder-decoder model and the "
            "cache manifest."
        ) from exc


def _build_cluster_pre_forward_guard(
    contract: ClusterFeatureContract,
    model: object,
) -> Callable[[], None]:
    """Validate fresh live checkpoint metadata at the first Stage 4 forward."""

    if not isinstance(getattr(model, "_loaded_meta_data", None), dict):
        raise AxBenchBaseError(
            "Clustered Stage 4 target is missing loaded checkpoint metadata"
        )
    @cache
    def _guard() -> None:
        # Read the model attribute at the forward boundary. Retaining the
        # mapping seen during bundle assembly would miss replacement or loss.
        loaded_metadata = getattr(model, "_loaded_meta_data", None)
        if not isinstance(loaded_metadata, dict):
            raise AxBenchBaseError(
                "Clustered Stage 4 target lost its loaded checkpoint metadata "
                "before first forward"
            )
        assert_loaded_cluster_target(
            contract,
            model,
            loaded_metadata,
            surface=(
                "AxBench-Base Stage 4 encoder-decoder checkpoint immediately "
                "before first forward"
            ),
        )

    return _guard


def _stage4_targets(
    *,
    decoder_only_model: object | None,
    encdec_model: object | None,
    decoder_only_meta: TargetModelMetadata | None,
    encdec_meta: TargetModelMetadata | None,
    nanochat_tokenizer: object,
    encdec_context_provider: ContextProvider | None,
    cluster_contract: ClusterFeatureContract | None = None,
) -> list[TargetBundle]:
    """Build bundles only for target models selected by the current config."""

    targets: list[TargetBundle] = []
    if decoder_only_model is not None:
        if decoder_only_meta is None:
            raise AxBenchBaseError("Decoder-only Stage 4 model metadata is missing")
        checkpoint_files_pin = getattr(
            decoder_only_model,
            "_loaded_checkpoint_files_pin",
            None,
        )
        if cluster_contract is not None and not isinstance(
            checkpoint_files_pin,
            CheckpointFilesPin,
        ):
            raise AxBenchBaseError(
                "Clustered decoder-only Stage 4 target is missing its exact "
                "loaded checkpoint pin"
            )
        targets.append(
            TargetBundle(
                name="decoder_only",
                model=decoder_only_model,
                meta=decoder_only_meta,
                tokenizer=nanochat_tokenizer,
                context_provider=None,
                cluster_contract=cluster_contract,
                checkpoint_files_pin=checkpoint_files_pin,
            )
        )
    elif decoder_only_meta is not None:
        raise AxBenchBaseError("Decoder-only Stage 4 metadata has no live model")

    if encdec_model is not None:
        if encdec_meta is None:
            raise AxBenchBaseError("Encoder-decoder Stage 4 model metadata is missing")
        if encdec_context_provider is None:
            raise AxBenchBaseError(
                "Encoder-decoder Stage 4 model has no context provider"
            )
        targets.append(
            TargetBundle(
                name="encdec",
                model=encdec_model,
                meta=encdec_meta,
                tokenizer=nanochat_tokenizer,
                context_provider=encdec_context_provider,
                cluster_contract=cluster_contract,
                cluster_pre_forward_guard=(
                    None
                    if cluster_contract is None
                    else _build_cluster_pre_forward_guard(
                        cluster_contract,
                        encdec_model,
                    )
                ),
            )
        )
    elif encdec_meta is not None or encdec_context_provider is not None:
        raise AxBenchBaseError(
            "Encoder-decoder Stage 4 metadata/provider has no live model"
        )
    return targets


def _configured_stage4_target_names(cfg: AxBenchBaseConfig) -> set[str]:
    """Return target families that can survive config-only method filters.

    Checkpoint-dependent negative-sampling eligibility remains in
    :func:`generate_all`; this helper only decides which heavy models and
    context cache can possibly be needed.
    """

    if cfg.enabled_methods is not None:
        for name in cfg.enabled_methods:
            get_method_by_name(name)
    for name in cfg.disabled_methods:
        get_method_by_name(name)

    target_names: set[str] = set()
    for method in ALL_METHODS:
        if not cfg.run_negative_mode and method.mode is SteeringMode.NEGATIVE:
            continue
        if cfg.enabled_methods is not None and method.name not in cfg.enabled_methods:
            continue
        if method.name in cfg.disabled_methods:
            continue
        if method.target_model not in {"decoder_only", "encdec"}:
            raise AxBenchBaseError(
                f"Stage 4 method {method.name!r} has unknown target "
                f"{method.target_model!r}"
            )
        target_names.add(method.target_model)
    return target_names


def _validate_stage4_concept_corpora(
    cfg: AxBenchBaseConfig, all_concept_ids: set[int],
) -> None:
    """Require complete corpus coverage for the authoritative concepts.

    The final filtered concept list defines the population. Presence in a
    synth corpus is only a fail-loud consistency check; it cannot silently
    create a second, mode-specific population.
    """
    assert cfg.run_tag is not None
    modes = [SteeringMode.POSITIVE]
    if cfg.run_negative_mode:
        modes.append(SteeringMode.NEGATIVE)
    output_paths = paths.AxBenchBasePaths.from_config(cfg)
    for mode in modes:
        require_complete_concept_population_from_corpus(
            output_paths.synth_training(mode),
            all_concept_ids,
            mode=mode,
            consumer="Stage 4 generation",
            positive_accept_threshold=(
                cfg.accept_threshold
                if mode is SteeringMode.POSITIVE
                else None
            ),
        )


def _run_single_stage(
    cfg: AxBenchBaseConfig,
    stage: Stage | str,
    state: RuntimeState,
) -> None:
    """Call the stage function for ``stage``.

    Every stage from 0a through 6 is wired here. Stages 0a and 6 do not
    load models. Stage 0b shares the feature-extraction model and SAE through
    ``state``; the remaining runtime stages request their resources through
    the same context-manager and accessor surface.

    Unknown stage names raise :class:`AxBenchBaseError`.

    ``stage`` may be passed as a :class:`Stage` member or the
    equivalent bare-string identifier; the call coerces on entry.

    Stage functions are looked up via the module-level names (e.g.
    ``cli.prepare_concept_list``, ``cli.train_diffmean_all``) so tests
    can ``monkeypatch.setattr(cli, "<name>", fake)`` and have the
    patched function picked up at dispatch time.
    """
    stage_enum = Stage.coerce(stage)

    # --- Early/final data-path stages --------------------------------
    if stage_enum is Stage.PREPARE_CONCEPTS:
        if state.cluster_contract is None:
            prepare_concept_list(cfg)
        else:
            prepare_concept_list(
                cfg,
                cluster_contract=state.cluster_contract,
            )
        return
    if stage_enum is Stage.PREPARE_SEED_POOLS:
        with state.base_model() as base_model, state.base_sae() as base_sae:
            prepare_seed_pools(
                cfg,
                base_model=base_model,
                base_sae=base_sae,
                rank=state.ddp_rank,
                world_size=state.ddp_world_size,
            )
        return
    if stage_enum is Stage.AGGREGATE:
        aggregate(cfg)
        return

    # --- Runtime-state stages (Phase 6) ------------------------------
    if stage_enum is Stage.PREPARE_NEGATIVE_PREFIXES:
        assert cfg.run_tag is not None
        concepts_path = paths.AxBenchBasePaths.from_config(cfg).candidate_concepts_json()
        # Resume short-circuit MUST be rank-0-decides + broadcast under
        # multi-rank: a divergent decision (rank 0 sees artifacts
        # complete and returns; rank 1 lags the filesystem and proceeds
        # into ``run_single_rank``) deadlocks on
        # ``dist.all_gather_object``. The broadcast pattern bounds rank
        # state to a single source of truth.
        #
        # Audit slice 16 (P1 / manifest §7): the broadcast logic is
        # delegated to ``_broadcast_resume_decision`` rather than
        # re-implemented here. Two implementations of the same
        # broadcast contract risk silent drift; the helper is the
        # single source of truth for both single- and multi-rank
        # paths.
        local_resume: Path | None = None
        local_resume_error: str | None = None
        if state.ddp_rank == 0:
            try:
                local_resume = resume_negative_prefixes_if_complete(cfg)
            except Exception as exc:
                local_resume_error = str(exc)
        broadcast_resume = _broadcast_resume_decision(
            local_resume,
            rank=state.ddp_rank,
            world_size=state.ddp_world_size,
            resume_error=local_resume_error,
        )
        if broadcast_resume is not None:
            return
        # Peak VRAM moment: Stage 0c now keeps only the base Gemma
        # feature-extraction model and the SAE live on device. The
        # target decoder-only and encoder-decoder models are intentionally
        # not loaded here. Verification generation and activation
        # measurement both run through the base SAE LM.
        #
        # PR-4: pass DDP coordinates from the RuntimeState so the
        # multi-GPU runner can partition candidates across ranks. Single-
        # GPU runs still use rank=0, world_size=1 (the dataclass
        # defaults).
        with state.base_model() as extraction_model, state.base_sae() as sae:
            cluster_kwargs: dict[str, Any] = (
                {}
                if state.cluster_contract is None
                else {"cluster_contract": state.cluster_contract}
            )
            prepare_negative_prefixes(
                cfg,
                concepts_path=concepts_path,
                base_model=extraction_model,
                base_sae=sae,
                target_model_meta=_stage0c_sae_metadata(cfg),
                rank=state.ddp_rank,
                world_size=state.ddp_world_size,
                **cluster_kwargs,
            )
        return

    if stage_enum is Stage.SYNTH_POSITIVE_MODE:
        with state.base_model() as extraction_model, state.base_sae() as sae:
            cluster_kwargs: dict[str, Any] = (
                {}
                if state.cluster_contract is None
                else {"cluster_contract": state.cluster_contract}
            )
            synthesize_positive_mode(
                cfg,
                concepts=state.concepts(),
                seeds_train=state.seeds_train(),
                seed_rows_sha256=state.seeds_train_rows_sha256(),
                base_model=extraction_model,
                base_sae=sae,
                target_model_meta=state.encdec_meta(),
                **cluster_kwargs,
            )
        return

    if stage_enum is Stage.SYNTH_NEGATIVE_MODE:
        if not cfg.run_negative_mode:
            logger.info(
                "Skipping Stage 1c (SYNTH_NEGATIVE_MODE): "
                "cfg.run_negative_mode=False",
            )
            return
        concepts = state.stage1b_concepts()
        with state.base_model() as extraction_model, state.base_sae() as sae:
            cluster_kwargs: dict[str, Any] = (
                {}
                if state.cluster_contract is None
                else {"cluster_contract": state.cluster_contract}
            )
            synthesize_negative_mode(
                cfg,
                concepts=concepts,
                base_model=extraction_model,
                base_sae=sae,
                target_model_meta=state.encdec_meta(),
                **cluster_kwargs,
            )
        return

    if stage_enum is Stage.CONCEPT_FEATURE_MAPPING:
        if cfg.concept_feature_mode == "canonical":
            if state.cluster_contract is None:
                concept_feature_mapping_canonical(
                    cfg,
                    concepts=state.downstream_concepts(),
                )
            else:
                concept_feature_mapping_canonical(
                    cfg,
                    concepts=state.downstream_concepts(),
                    cluster_contract=state.cluster_contract,
                )
        elif cfg.concept_feature_mode == "delta_ranked":
            output_paths = state.output_paths()
            pos_corpus = output_paths.synth_training_positive()
            neg_corpus: Path | None = (
                output_paths.synth_training_negative() if cfg.run_negative_mode else None
            )
            with state.base_model() as extraction_model, state.base_sae() as sae:
                concept_feature_mapping_delta_ranked(
                    cfg,
                    concepts=state.downstream_concepts(),
                    synth_training_positive_path=pos_corpus,
                    synth_training_negative_path=neg_corpus,
                    base_model=extraction_model,
                    base_sae=sae,
                    target_model_meta=state.encdec_meta(),
                )
        else:
            raise AxBenchBaseError(
                f"Unknown concept_feature_mode: "
                f"{cfg.concept_feature_mode!r}. "
                f"Expected 'canonical' or 'delta_ranked'."
            )
        return

    if stage_enum is Stage.TRAIN_DIFFMEAN:
        _run_scalar_baseline_training(
            cfg, state,
            trainer=train_diffmean_all,
            # Both targets, clustered or not. The clustered path used to train
            # decoder_only ONLY, which silently made encdec targets
            # un-counter-steerable: `requirements_from_candidate_rows` asks for
            # the counter direction in the ROW'S OWN target coordinates whenever
            # `adversarial_strength != 0`, so an encdec row at non-zero strength
            # needs `<family>/encdec/`. The gap was invisible at
            # `magnitudes: [0.0]` (the requirement is gated on strength) and
            # surfaced only as a preflight failure mid-sweep.
            #
            # Both FAMILIES are fixed, not just diffmean, because
            # `counter_direction_family` is `Literal["diffmean", "linear_probe"]`
            # -- fixing only diffmean would leave the linear_probe setting broken
            # on clustered sources in exactly the same silent way.
            targets=("decoder_only", "encdec"),
        )
        return

    if stage_enum is Stage.TRAIN_LINEAR_PROBE:
        _run_scalar_baseline_training(
            cfg, state,
            trainer=train_linear_probe_all,
            # Both targets, clustered or not. The clustered path used to train
            # decoder_only ONLY, which silently made encdec targets
            # un-counter-steerable: `requirements_from_candidate_rows` asks for
            # the counter direction in the ROW'S OWN target coordinates whenever
            # `adversarial_strength != 0`, so an encdec row at non-zero strength
            # needs `<family>/encdec/`. The gap was invisible at
            # `magnitudes: [0.0]` (the requirement is gated on strength) and
            # surfaced only as a preflight failure mid-sweep.
            #
            # Both FAMILIES are fixed, not just diffmean, because
            # `counter_direction_family` is `Literal["diffmean", "linear_probe"]`
            # -- fixing only diffmean would leave the linear_probe setting broken
            # on clustered sources in exactly the same silent way.
            targets=("decoder_only", "encdec"),
        )
        return

    if stage_enum is Stage.TRAIN_PROMPTING:
        write_prompting_descriptions(
            cfg,
            concepts=state.downstream_concepts(),
        )
        return

    if stage_enum is Stage.TRAIN_LORA:
        _run_scalar_baseline_training(
            cfg, state,
            trainer=train_lora_all,
            targets=("decoder_only",),
        )
        return

    if stage_enum is Stage.ENUMERATE_STAGE4_CONTEXTS:
        tokenizer = state.nanochat_tokenizer()
        seeds_eval = state.seeds_eval()
        eval_seeds_negative = seeds_eval if cfg.run_negative_mode else []
        concepts = state.downstream_concepts()
        _validate_stage4_concept_corpora(
            cfg, {concept.concept_id for concept in concepts}
        )
        with state.encdec_model() as encdec_model:
            enumerate_stage4_contexts(
                cfg,
                concepts=concepts,
                eval_seeds_positive=seeds_eval,
                eval_seeds_negative=eval_seeds_negative,
                tokenizer=tokenizer,
                encdec_meta=state.encdec_meta(),
                encdec_sequence_len=_encdec_model_sequence_len(encdec_model),
                cluster_contract=state.cluster_contract,
            )
        return

    if stage_enum is Stage.JUDGE:
        judge_all(
            cfg,
            concepts=state.downstream_concepts(),
            client=state.judge_client(),
        )
        return

    if stage_enum is Stage.GENERATE:
        # Stage 4 keeps each selected target model resident while
        # ``_stage4_targets`` builds the generation wrapper consumed by
        # ``generate_all``. Exiting the stack CPU-offloads both models.
        #
        # ``seeds_eval()`` is reused for both positive and negative
        # modes until Stage 0b is extended to produce a distinct
        # ``eval_seeds_negative`` pool. This matches the Phase-6
        # integration test harness in
        # ``tests.axbench_base.integration.test_full_pipeline_dev_tier``,
        # which also uses the same row shape for both pools, and keeps
        # Stage 4 unblocked while the eventual mode-specific negative
        # pool is spec'd.
        #
        # Defense-in-depth: when run_negative_mode=False, pass an empty
        # negative seed list so that even if the method filter had a
        # regression, no negative-mode generation would find seeds to
        # iterate.  The filter already excludes negative methods, so
        # this list is never consumed in practice.
        nanochat_tokenizer = state.nanochat_tokenizer()
        seeds_eval = state.seeds_eval()
        eval_seeds_neg = seeds_eval if cfg.run_negative_mode else []
        assert cfg.run_tag is not None
        concepts = state.downstream_concepts()
        _validate_stage4_concept_corpora(
            cfg, {concept.concept_id for concept in concepts}
        )
        configured_targets = _configured_stage4_target_names(cfg)
        with ExitStack() as model_stack:
            decoder_only_model = None
            decoder_only_meta = None
            if "decoder_only" in configured_targets:
                decoder_only_model = model_stack.enter_context(
                    state.decoder_only_model()
                )
                decoder_only_meta = state.decoder_only_meta()

            encdec_model = None
            encdec_meta = None
            encdec_context_provider = None
            if "encdec" in configured_targets:
                encdec_model = model_stack.enter_context(state.encdec_model())
                encdec_meta = state.encdec_meta()
                # Build the cache-backed provider inside the same residency
                # block that runs generation. Decoder-only-only method plans
                # never load this model or require an unused context cache.
                encdec_context_provider = _build_stage4_encdec_context_provider(
                    cfg,
                    encdec_model=encdec_model,
                    encdec_meta=encdec_meta,
                    cluster_contract=state.cluster_contract,
                )
            targets = _stage4_targets(
                decoder_only_model=decoder_only_model,
                encdec_model=encdec_model,
                decoder_only_meta=decoder_only_meta,
                encdec_meta=encdec_meta,
                nanochat_tokenizer=nanochat_tokenizer,
                encdec_context_provider=encdec_context_provider,
                cluster_contract=state.cluster_contract,
            )
            generate_all(
                cfg,
                concepts=concepts,
                targets=targets,
                eval_seeds_positive=seeds_eval,
                eval_seeds_negative=eval_seeds_neg,
                apply_max_act_scale=True,
                inactive_sampler=(
                    state.inactive_sampler()
                    if "encdec" in configured_targets
                    else None
                ),
            )
        return

    # Every stage in :data:`_ALL_STAGES_IN_ORDER` is dispatched above,
    # so reaching this fallthrough means the caller either passed
    # :attr:`Stage.ALL` directly (which must have been expanded upstream
    # by :func:`_resolve_stage_list`) or an unknown identifier. Both
    # are bugs.
    raise AxBenchBaseError(
        f"Unknown stage {stage_enum.value!r}. Known stages: "
        f"{sorted(s.value for s in _ALL_STAGES_IN_ORDER)}."
    )


def _dispatch_stage(cfg: AxBenchBaseConfig, state: RuntimeState) -> None:
    """Run the stage(s) requested by ``cfg.stage``.

    For each stage, the dispatcher:

    1. resolves the artifact dep set via
       :func:`check_stage_dependencies` — this raises
       :class:`AxBenchBaseError` if any required on-disk artifact is
       missing, with a multi-line message listing every missing path;
    2. calls :func:`_run_single_stage` with the shared
       :class:`RuntimeState` instance.

    The dep check runs BEFORE the stage body, so a missing prerequisite
    never gets as far as loading models or building a client.

    Multi-GPU semantics (PR-4 review hardening): every stage that is
    NOT in :data:`_RANK_AWARE_STAGES` runs on rank 0 only when
    ``world_size > 1``. Each rank enters exactly one collective per
    stage: rank-aware stages rendezvous through :func:`_maybe_barrier`,
    while rank-0-only stages broadcast rank 0's outcome so failures
    reach every rank instead of stranding workers in a bare barrier.
    """
    stages = _resolve_stage_list(cfg.stage, cfg.run_negative_mode)
    for stage_name in stages:
        rank0_collective = (
            stage_name not in _RANK_AWARE_STAGES
            and state.ddp_world_size > 1
            and dist.is_available()
            and dist.is_initialized()
        )
        if rank0_collective:
            failure: Exception | None = None
            if state.ddp_rank == 0:
                try:
                    # The stage region is rank-0-only when the stage itself is.
                    # Keep profiler entry, exit, and event emission inside the
                    # same failure boundary as the work so teardown failures
                    # are converted into the one outcome every rank observes.
                    # The control-plane outcome broadcast therefore follows
                    # profiler teardown; the region retains the nested stage
                    # work and dependency-check timing.
                    with profile_region(
                        f"stage.{stage_name.value}",
                        stage=stage_name.value,
                    ):
                        with profile_region(
                            "stage.dependency_check",
                            stage=stage_name.value,
                        ):
                            check_stage_dependencies(cfg, stage_name)
                        _run_single_stage(cfg, stage_name, state)
                except Exception as exc:
                    failure = exc
            _broadcast_rank0_stage_outcome(
                stage_name,
                rank=state.ddp_rank,
                world_size=state.ddp_world_size,
                failure=failure,
            )
            continue
        with profile_region(
            f"stage.{stage_name.value}",
            stage=stage_name.value,
        ):
            if not _stage_runs_on_rank(stage_name, rank=state.ddp_rank):
                # Rank > 0 in a non-rank-aware stage: barrier and skip.
                logger.info(
                    "[axbench-base] rank {r}/{w} skipping stage {s} "
                    "(rank-0-only under DDP)",
                    r=state.ddp_rank, w=state.ddp_world_size,
                    s=stage_name.value,
                )
                _maybe_barrier(state.ddp_world_size)
                continue
            with profile_region(
                "stage.dependency_check",
                stage=stage_name.value,
            ):
                check_stage_dependencies(cfg, stage_name)
            _run_single_stage(cfg, stage_name, state)
            # Sync after every stage so the next stage starts with a
            # coherent on-disk view across ranks.
            _maybe_barrier(state.ddp_world_size)


def _resolve_ddp_coordinates() -> tuple[int, int]:
    """Resolve (rank, world_size) from the active distributed group.

    Reads from :func:`torch.distributed.get_rank` /
    :func:`torch.distributed.get_world_size` when the process group is
    initialised (which :func:`_run` ensures via
    :func:`nanochat.common.compute_init` BEFORE this helper is called).

    Single-GPU runs (no torchrun launch) return ``(0, 1)`` —
    ``compute_init`` falls through without calling
    ``init_process_group`` for that case, so the default applies.
    """
    if dist.is_available() and dist.is_initialized():
        return dist.get_rank(), dist.get_world_size()
    return 0, 1


def _run(cfg: DictConfig) -> None:
    """The testable inner of :func:`main`.

    Separated from ``main`` so tests can call it with a hand-built
    ``DictConfig`` without going through Hydra's argparse path.

    The environment validation runs BEFORE ``_dispatch_stage`` so
    missing credentials (e.g. ``OPENROUTER_API_KEY``) surface to the
    operator immediately, rather than after a 30-second model download
    or a half-finished stage. See
    :func:`runtime_state.validate_env_for_stages` for the contract.

    The :class:`RuntimeState` instance is constructed once per run and
    torn down in a ``try/finally`` so cached weights are dropped and
    the CUDA allocator cache is emptied on every exit path (success
    OR failure).

    PR-4 review hardening: this CLI now calls
    :func:`nanochat.common.compute_init` to initialise the distributed
    process group when launched under torchrun. Without this call, every
    rank would silently see ``rank=0, world_size=1`` and race-write the
    same on-disk artifacts. ``compute_init`` is a no-op for single-GPU
    runs (no ``RANK``/``WORLD_SIZE`` env vars set) — it falls through to
    a plain ``torch.device(device_type)`` without calling
    ``init_process_group``.

    The companion :func:`nanochat.common.compute_cleanup` runs in the
    outer ``finally`` so the process group is destroyed on every exit
    path, including exceptions.
    """
    cfg_obj = cfg_to_dataclass(cfg)
    validate_config(cfg_obj)
    contract_request = _cluster_contract_request(cfg_obj)
    run_tag_generated = False
    run_tag_synchronized = False
    legacy_preflight_complete = False
    if contract_request is None and cfg_obj.run_tag is None:
        cfg_obj = cfg_obj.replace(run_tag=_generate_run_tag(cfg_obj))
        run_tag_generated = True
    # A known single-process tag can reject the historical split before even
    # environment or distributed initialization. Under torchrun, defer to the
    # collective rank-0 decision below so ranks cannot diverge on filesystem
    # visibility.
    if cfg_obj.run_tag is not None and os.environ.get("WORLD_SIZE", "1") == "1":
        paths.assert_no_legacy_output_shadow(cfg_obj)
        legacy_preflight_complete = True
    stages = _resolve_stage_list(cfg_obj.stage, cfg_obj.run_negative_mode)
    if contract_request is None:
        # Preserve the legacy order exactly. Clustered runs defer this until
        # malformed provenance has had the first opportunity to fail.
        validate_env_for_stages(stages, cfg=cfg_obj)
    # Initialise the distributed process group when launched under
    # torchrun. ``compute_init`` returns ``(is_ddp, rank, local_rank,
    # world_size, device)``; we only need ``rank`` / ``world_size``
    # downstream — the per-rank device assignment is handled by the
    # individual stage runners that load heavy models.
    # axbench-base's Stage 0a runs a ~25-min serial Neuronpedia fetch on
    # rank 0 while other ranks are barriered; the default NCCL collective
    # timeout (~10 min) would trip. Opt THIS pipeline in to a longer
    # process-group timeout without changing the global default for other
    # DDP jobs (operators can still override via the env).
    os.environ.setdefault("NCCL_TIMEOUT_SEC", "1800")
    state: RuntimeState | None = None
    state_close_attempted = False
    try:
        _, _, ddp_local_rank, _, device = compute_init(
            device_type=_device_type_from_cfg(cfg_obj.device)
        )
        ddp_rank, ddp_world_size = _resolve_ddp_coordinates()
        _assert_ddp_output_root_agreement(
            cfg_obj,
            world_size=ddp_world_size,
        )
        cluster_contract: ClusterFeatureContract | None = None
        if contract_request is not None:
            if cfg_obj.run_tag is not None and not legacy_preflight_complete:
                cfg_obj = _synchronize_ddp_run_tag(
                    cfg_obj,
                    rank=ddp_rank,
                    world_size=ddp_world_size,
                    generated=False,
                )
                run_tag_synchronized = True
                _assert_no_legacy_output_shadow_ddp(
                    cfg_obj,
                    rank=ddp_rank,
                    world_size=ddp_world_size,
                )
                legacy_preflight_complete = True
            cluster_contract = resolve_cluster_feature_contract_ddp(
                contract_request
            )
            cfg_obj = cfg_obj.replace(
                encdec={
                    **cfg_obj.encdec,
                    "step": cluster_contract.checkpoint.step,
                }
            )
            if cfg_obj.run_tag is None:
                cfg_obj = cfg_obj.replace(run_tag=_generate_run_tag(cfg_obj))
                run_tag_generated = True
            validate_env_for_stages(stages, cfg=cfg_obj)
        assert cfg_obj.run_tag is not None
        if not run_tag_synchronized:
            cfg_obj = _synchronize_ddp_run_tag(
                cfg_obj,
                rank=ddp_rank,
                world_size=ddp_world_size,
                generated=run_tag_generated,
            )
        if not legacy_preflight_complete:
            _assert_no_legacy_output_shadow_ddp(
                cfg_obj,
                rank=ddp_rank,
                world_size=ddp_world_size,
            )
        output_paths = paths.AxBenchBasePaths.from_config(cfg_obj)
        _install_cluster_marker_ddp(
            cfg_obj,
            cluster_contract,
            rank=ddp_rank,
            world_size=ddp_world_size,
        )
        state = RuntimeState(
            cfg=cfg_obj,
            ddp_rank=ddp_rank,
            ddp_world_size=ddp_world_size,
            cluster_contract=cluster_contract,
        )
        profile_output_dir = (
            Path(cfg_obj.profile.output_dir)
            if cfg_obj.profile.output_dir is not None
            else output_paths.profile_dir()
        )
        profile_gpu_device_index = resolve_profile_gpu_device_index(
            cfg_obj.device,
            ddp_local_rank=ddp_local_rank,
            ddp_world_size=ddp_world_size,
        )
        profile_metadata = {
            "pipeline": "axbench_base",
            "run_tag": cfg_obj.run_tag,
            "stage": cfg_obj.stage,
            "stages": [stage.value for stage in stages],
            "configured_output_root": cfg_obj.output_root,
            "effective_output_root": str(output_paths.output_root),
            "run_output_root": str(output_paths.run_output_root()),
            "feature_dir": cfg_obj.feature_dir,
            "feature_statistics_path": cfg_obj.feature_statistics_path,
            "ddp_rank": ddp_rank,
            "ddp_world_size": ddp_world_size,
            "ddp_local_rank": ddp_local_rank,
            "profile_gpu_device_index": profile_gpu_device_index,
            "device": str(device),
            "config": axbench_base_config_to_dict(cfg_obj),
        }
        profile_cm = (
            AxBenchProfiler(
                profile_output_dir,
                metadata=profile_metadata,
                synchronize_cuda=cfg_obj.profile.synchronize_cuda,
                gpu_utilization=cfg_obj.profile.gpu_utilization,
                gpu_poll_interval_ms=cfg_obj.profile.gpu_poll_interval_ms,
                gpu_idle_threshold=cfg_obj.profile.gpu_idle_threshold,
                gpu_device_index=profile_gpu_device_index,
            )
            if cfg_obj.profile.enabled and ddp_rank == 0
            else nullcontext()
        )
        with profile_cm:
            try:
                _dispatch_stage(cfg_obj, state)
            finally:
                # Mark the attempt first: if close itself raises, the outer
                # teardown must preserve that exception instead of retrying
                # the same non-idempotent failure.
                state_close_attempted = True
                state.close()
    finally:
        try:
            # Profile setup and context entry can fail after RuntimeState owns
            # caches/models but before the inner dispatch finally is active.
            if state is not None and not state_close_attempted:
                state_close_attempted = True
                state.close()
        finally:
            # This is safe even when compute_init failed before creating a
            # process group, and destroys a partially initialized group when
            # compute_init raised after init_process_group.
            compute_cleanup()


@hydra.main(
    version_base=None,
    config_path="../../configs/eval/axbench_base",
    config_name="axbench_base",
)
def main(cfg: DictConfig) -> None:
    """CLI entry point — see module docstring for usage."""
    _run(cfg)


