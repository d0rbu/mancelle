"""Hydra-decorated CLI entry point for the AxBench-Base evaluation pipeline.

Usage::

    uv run python -m scripts.eval.axbench_base_eval \
        feature_dir=out/data/features/s128/l8/a_res/p_max_pool/f16k/m_gemma-2-2b/base \
        feature_statistics_path=out/data/features/s128/l8/a_res/p_max_pool/f16k/m_gemma-2-2b/base/feature_statistics.safetensors \
        decoder_only.source=base decoder_only.model_tag=d12_base \
        decoder_only.step=54600 \
        encdec.source=encdec encdec.model_tag=d12_baseline \
        encdec.step=54600

The CLI loads the Hydra config tree at ``configs/eval/axbench_base/``,
converts it into an :class:`AxBenchBaseConfig` dataclass, validates it,
auto-generates a ``run_tag`` if none was supplied, runs the
:func:`validate_env_for_stages` pre-flight check against the resolved
stage list, constructs a single
:class:`~steering.eval.axbench_base.runtime_state.RuntimeState` for the
heavy-model lifecycle, and then dispatches the requested stage(s).

Stage coverage
--------------

This CLI implements every stage from 0a through 6. The fourteen
:class:`Stage` values (0a, 0b, 0c, 1b, 1c, 2, 3a, 3b, 3c, 3d, 3e,
4, 5, 6) plus the ``all`` pseudo-stage are each dispatched from a branch
in :func:`_run_single_stage`. Every stage that touches a heavy resource
requests it from the shared :class:`RuntimeState` via a context manager
or plain accessor; pure-data stages 0a and 6 do not load a model.

:class:`RuntimeState` owns all runtime-only state:

- the feature-extraction base model + SAE pair (loaded from Neuronpedia / HF)
- the decoder-only and encoder-decoder target models
- the OpenRouter judge client for Stage 5
- ``TargetModelMetadata`` detected once per run for each target
- the inactive-feature sampler derived from the encdec's
  training-time ``user_config["negative_selection"]``

:func:`_build_inactive_sampler` in ``runtime_state.py`` is fully wired
and returns a callable with the ``(*, rng: random.Random) -> dict[int, int]``
signature Stage 4's :func:`build_mode_aware_encoder_input` expects;
internally it bridges ``random.Random`` to :class:`torch.Generator`
so the orchestrator's existing RNG API is preserved.

RuntimeState lifecycle inside ``_run``
--------------------------------------

:func:`_run` is the testable inner. It:

1. materialises the :class:`AxBenchBaseConfig` via
   :func:`cfg_to_dataclass` and validates it;
2. fills in an autogenerated ``run_tag`` (``YYYYMMDD-HHMMSS-<8charhex>``)
   when ``cfg.run_tag is None``;
3. resolves the stage list via :func:`_resolve_stage_list`, which
   expands ``Stage.ALL`` and drops :attr:`Stage.SYNTH_NEGATIVE_MODE`
   when ``cfg.run_negative_mode is False``;
4. calls :func:`validate_env_for_stages` BEFORE any heavy load so
   missing credentials surface immediately, not after a 30-second
   model download;
5. constructs a single :class:`RuntimeState` for the run;
6. wraps :func:`_dispatch_stage` in ``try/finally`` so
   :meth:`RuntimeState.close` always runs and the CUDA allocator cache
   is emptied on every exit path.

The dispatcher calls :func:`check_stage_dependencies` BEFORE each
stage body so a missing prerequisite never gets as far as loading
models. Stages that need heavy resources request them via the
refcounted ``with`` blocks on :class:`RuntimeState`; nested contexts
share the single loaded instance, and ``close()`` refuses to run while
any refcount is non-zero so escaped context blocks get caught at
teardown.

See :doc:`../docs/axbench_base_advanced` for the full design contract
of :class:`RuntimeState`, the per-stage resource matrix, the CPU
offload strategy, and the three-tier test layout.

Design notes
------------

- ``_run`` is the testable inner function. ``main`` is just a Hydra
  wrapper around it so the tests can call ``_run`` directly with a
  hand-built ``DictConfig`` without triggering Hydra's argparse layer.
- Imports are ALL at module scope per the project's hard rule — no
  conditional imports, no imports inside functions.
- ``run_tag`` is auto-generated as ``YYYYMMDD-HHMMSS-<8 char hash>`` so
  that two successive runs with the same config land in the same
  output directory only if they start within the same second.
"""

