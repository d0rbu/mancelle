def _cluster_target_kwargs(
    cluster_target: ClusterFeatureTarget | None,
) -> dict[str, Any]:
    return {} if cluster_target is None else {"cluster_target": cluster_target}


def _cluster_cache_suffix(cluster_target: ClusterFeatureTarget | None) -> str:
    if cluster_target is None:
        return ""
    return f"_fc{cluster_target.feature_contract_fingerprint}"


def _stage1c_continuation_request(
    template: str,
    *,
    concept: Concept,
    prefix_row: dict[str, Any],
    attempt: int,
    cluster_target: ClusterFeatureTarget | None,
) -> Stage1ContinuationRequest:
    """Build one deterministic Stage 1c avoiding request."""
    prefix_text = str(prefix_row["prefix_text"])
    cluster_fingerprint = (
        None
        if cluster_target is None
        else cluster_target.feature_contract_fingerprint
    )
    return build_stage1_continuation_request(
        template,
        label="Stage 1c concept_avoiding",
        kind="STAGE1C_AVOID",
        identity={
            "stage": "1c",
            "content_class": CONCEPT_AVOIDING_LABEL,
            "concept_id": concept.concept_id,
            "feature_id": concept.feature_index,
            "prefix_source_shard": int(prefix_row["prefix_source_shard"]),
            "prefix_source_doc": int(prefix_row["prefix_source_doc"]),
            "prefix_source_seg_idx": int(prefix_row["prefix_activating_seg_idx"]),
            "attempt": attempt,
            "prefix_sha256": hashlib.sha256(prefix_text.encode("utf-8")).hexdigest(),
            "feature_contract_fingerprint": cluster_fingerprint,
        },
        prefix_text=prefix_text,
        description=concept.description,
    )


_NEG_SYNTH_SEED_OFFSET = 0xE90001  # distinct from positive-mode and verification offsets


@dataclass
class _NegativePending:
    order: int
    concept: Concept
    prefix_row: dict[str, Any]
    rich_rows: list[dict[str, Any]]
    accepted_row: dict[str, Any] | None = None

    @property
    def done(self) -> bool:
        return self.accepted_row is not None


@dataclass
class _PreparedNegativeBatchResult:
    position: int
    request: SynthRequestWithPayload
    result: SynthResult
    item: _NegativePending
    continuation_request: Stage1ContinuationRequest
    attempt: int
    continuation: str | None = None
    outcome: AvoidContinuationOutcome | None = None


def _negative_chain_request(
    cfg: AxBenchBaseConfig,
    template: str,
    item: _NegativePending,
    *,
    attempt: int,
    cluster_target: ClusterFeatureTarget | None,
) -> SynthRequest:
    continuation_request = _stage1c_continuation_request(
        template,
        concept=item.concept,
        prefix_row=item.prefix_row,
        attempt=attempt,
        cluster_target=cluster_target,
    )
    return SynthRequestWithPayload(
        index=item.order,
        prompt=continuation_request.prompt,
        cache_key=make_cache_key(
            model=cfg.synth.model,
            prompt=continuation_request.prompt,
            tag=(
                f"neg_c{item.concept.concept_id}"
                f"_d{item.prefix_row['prefix_source_doc']}"
                f"_a{attempt}"
                f"{_cluster_cache_suffix(cluster_target)}"
            ),
        ),
        attrs={
            "concept_id": item.concept.concept_id,
            "attempt": attempt,
            "prefix_source_doc": item.prefix_row["prefix_source_doc"],
        },
        payload=continuation_request,
    )


