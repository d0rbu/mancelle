def _load_negative_prefixes(
    cfg: AxBenchBaseConfig,
    *,
    feature_contract_fingerprint: str | None = None,
) -> list[dict[str, Any]]:
    """Load the Stage 0c ``negative_mode_prefixes.parquet`` as a list of row dicts.

    Raises ``AxBenchBaseError`` if the parquet does not exist at the
    expected path (Stage 0c has not been run yet).
    """
    if cfg.run_tag is None:
        raise AxBenchBaseError(
            "cfg.run_tag must be set before loading Stage 0c negative prefixes"
        )
    output_paths = paths.AxBenchBasePaths.from_config(cfg)
    path = output_paths.negative_mode_prefixes()
    if not path.exists():
        raise AxBenchBaseError(
            f"Negative-mode prefixes parquet not found at {path}; Stage 0c must run before Stage 1c"
        )
    if feature_contract_fingerprint is not None:
        return _read_cluster_pinned_negative_prefixes(
            cfg,
            path=path,
            expected_fingerprint=feature_contract_fingerprint,
        )
    validate_negative_prefixes_extractor_identity_metadata(
        path,
        cfg=cfg,
        consumer="Stage 1c",
    )
    validate_negative_prefixes_tokenizer_metadata(
        path,
        expected_tokenizer_id=cfg.extraction_tokenizer_id,
        consumer="Stage 1c",
    )
    return pq.read_table(path).to_pylist()


def _read_cluster_pinned_negative_prefixes(
    cfg: AxBenchBaseConfig,
    *,
    path: Path,
    expected_fingerprint: str,
) -> list[dict[str, Any]]:
    """Read, verify, validate, and parse one exact Stage-0c byte snapshot."""

    try:
        stable_digest = stream_hash_file_stable(path)
        payload = stable_digest.path.read_bytes()
    except Exception as exc:
        raise AxBenchBaseError(
            "Could not read a stable clustered Stage 0c negative-prefix "
            f"artifact at {path}. Regenerate it under a fresh run tag."
        ) from exc
    if (
        len(payload) != stable_digest.byte_length
        or hashlib.sha256(payload).hexdigest() != stable_digest.sha256
    ):
        raise AxBenchBaseError(
            "Clustered Stage 0c negative-prefix artifact changed between "
            f"stable hashing and immutable read: {path}. Regenerate it "
            "under a fresh run tag."
        )
    try:
        table = pq.read_table(pa.BufferReader(payload))
    except Exception as exc:
        raise AxBenchBaseError(
            f"Could not parse clustered Stage 0c negative prefixes at {path}. "
            "Regenerate them under a fresh run tag."
        ) from exc

    validate_negative_prefixes_extractor_identity_metadata(
        path,
        cfg=cfg,
        consumer="Stage 1c",
        schema=table.schema,
    )
    validate_negative_prefixes_tokenizer_metadata(
        path,
        expected_tokenizer_id=cfg.extraction_tokenizer_id,
        consumer="Stage 1c",
        schema=table.schema,
    )
    actual_fingerprint = (table.schema.metadata or {}).get(b"feature_contract_fingerprint")
    if actual_fingerprint != expected_fingerprint.encode("utf-8"):
        raise AxBenchBaseError(
            "Clustered Stage 1c rejects Stage 0c prefixes with an absent or "
            "mismatched feature-contract fingerprint"
        )
    return table.to_pylist()


def _stable_hash_int(text: str, mod: int = 1000) -> int:
    """Deterministic ``0..mod-1`` hash of ``text`` via sha256.

    Replaces Python's ``hash(text) % mod``, which is session-dependent
    when ``PYTHONHASHSEED`` randomization is enabled (the default on
    CPython 3). The first 8 hex chars of the sha256 digest are parsed
    as an int and reduced modulo ``mod``.
    """
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:8]
    return int(digest, 16) % mod


def _exact_output_start(prefix_text: str, output_text: str) -> int:
    """Return the owned-BOS-inclusive output boundary for one synth pair."""

    _tokens, output_start = tokenize_labeled_pair(get_tokenizer(), prefix_text, output_text)
    return output_start


def _copy_concept_rich_rows(
    concept: Concept,
    prefix_row: dict[str, Any],
    cfg: AxBenchBaseConfig,
) -> list[dict[str, Any]]:
    """Emit one row per passing verification continuation from Stage 0c.

    These rows require no LLM call and no QC — the verification
    continuations were generated by the target decoder-only base model
    in Stage 0c and already passed the ``verification_percentile_threshold``
    consistency check.
    """
    dec = cfg.decoder_only
    gen_source = f"local:{dec.get('source', 'unknown')}/{dec.get('model_tag', 'unknown')}"
    rows: list[dict[str, Any]] = []
    conts = prefix_row["verification_continuations"]
    pcts = prefix_row["verification_percentiles"]
    for cont, pct in zip(conts, pcts, strict=True):
        rows.append(
            {
                "concept_id": concept.concept_id,
                "category": "positive",  # per spec: concept_rich side of negative mode
                "content_class": CONCEPT_RICH_LABEL,
                "prefix_text": prefix_row["prefix_text"],
                "output_text": cont,
                "output_concept": concept.description,
                "n_prefix_nanochat_tokens": _exact_output_start(prefix_row["prefix_text"], cont),
                "gen_source": gen_source,
                "gen_seed": -1,  # copied from verification; no new draw
                "qc_feature_id": concept.feature_index,
                "qc_seed_percentile": float("nan"),
                "qc_output_percentile": float(pct),
                "qc_delta": float("nan"),
                "qc_attempts": 0,
                "qc_accepted": True,
                "prefix_source_shard": int(prefix_row["prefix_source_shard"]),
                "prefix_source_doc": int(prefix_row["prefix_source_doc"]),
                "prefix_source_seg_idx": int(prefix_row["prefix_activating_seg_idx"]),
                "qc_zero_activation_verified": False,
            }
        )
    return rows


def _make_concept_avoiding_row(
    concept: Concept,
    prefix_row: dict[str, Any],
    continuation: str,
    attempts: int,
    cfg: AxBenchBaseConfig,
    zero_activation_verified: bool,
) -> dict[str, Any]:
    """Build a ``concept_avoiding`` row dict with the 19-column schema."""
    gen_seed = (
        cfg.generation.master_seed
        + _NEG_SYNTH_SEED_OFFSET
        + concept.concept_id * 1_000_000
        + _stable_hash_int(prefix_row["prefix_text"])
    )
    return {
        "concept_id": concept.concept_id,
        "category": "negative",
        "content_class": CONCEPT_AVOIDING_LABEL,
        "prefix_text": prefix_row["prefix_text"],
        "output_text": continuation,
        "output_concept": concept.description,
        "n_prefix_nanochat_tokens": _exact_output_start(prefix_row["prefix_text"], continuation),
        "gen_source": f"openrouter:{cfg.synth.model}",
        "gen_seed": gen_seed,
        "qc_feature_id": concept.feature_index,
        "qc_seed_percentile": float("nan"),
        "qc_output_percentile": float("nan"),
        "qc_delta": float("nan"),
        "qc_attempts": attempts,
        "qc_accepted": True,
        "prefix_source_shard": int(prefix_row["prefix_source_shard"]),
        "prefix_source_doc": int(prefix_row["prefix_source_doc"]),
        "prefix_source_seg_idx": int(prefix_row["prefix_activating_seg_idx"]),
        "qc_zero_activation_verified": zero_activation_verified,
    }


def _synthesize_concept_avoiding_row(
    concept: Concept,
    prefix_row: dict[str, Any],
    cfg: AxBenchBaseConfig,
    base_model: Any,
    base_sae: Any,
    llm_client: SynthCompleter,
    tokenizer: Any,
    template: str,
    *,
    sae_layer: int,
    cluster_target: ClusterFeatureTarget | None = None,
) -> dict[str, Any] | None:
    """Run the strict-zero QC retry loop for one ``concept_avoiding`` row.

    Returns the row dict on acceptance, or ``None`` on exhaustion
    (caller handles fallback).
    """
    f_c = concept.feature_index
    last_continuation = ""
    for attempt in range(cfg.max_retries + 1):
        request = _stage1c_continuation_request(
            template,
            concept=concept,
            prefix_row=prefix_row,
            attempt=attempt,
            cluster_target=cluster_target,
        )
        # The ``tag`` portion of the cache key includes ``attempt`` so
        # retries get fresh responses rather than hitting a cache entry
        # written by the prior failing attempt.
        cache_key = make_cache_key(
            model=cfg.synth.model,
            prompt=request.prompt,
            tag=(
                f"neg_c{concept.concept_id}"
                f"_d{prefix_row['prefix_source_doc']}_a{attempt}"
                f"{_cluster_cache_suffix(cluster_target)}"
            ),
        )
        try:
            with profile_region(
                "stage1c.synth_llm_complete",
                concept_id=concept.concept_id,
                attempt=attempt,
            ):
                response_text = llm_client.complete(
                    request.prompt,
                    cache_key=cache_key,
                )
        except AxBenchBaseError as exc:
            logger.warning(
                f"Concept {concept.concept_id} negative-synth attempt {attempt + 1}: "
                f"synth LLM call failed: {exc}"
            )
            continue
        with profile_region(
            "stage1c.parse_synth_response",
            concept_id=concept.concept_id,
            attempt=attempt,
        ):
            continuation = parse_stage1_continuation_or_none(
                prefix_text=prefix_row["prefix_text"],
                response=response_text,
                request=request,
                output_length=cfg.output_length,
                tokenizer=tokenizer,
                subject="Stage 1c concept_avoiding continuation",
                log_label=(f"Concept {concept.concept_id} negative-synth attempt {attempt + 1}"),
                protocol_counter="stage1c.continuation_protocol_failures",
                special_token_counter="stage1c.special_token_refusals",
                counter_attrs={
                    "concept_id": concept.concept_id,
                    "attempt": attempt,
                    "content_class": CONCEPT_AVOIDING_LABEL,
                },
            )
        # A refused (special-token-polluted) generation is retryable: skip this
        # attempt and loop to a fresh cache key, as a failed LLM call does.
        if continuation is None:
            continue
        last_continuation = continuation
        with profile_region(
            "stage1c.strict_zero_qc",
            concept_id=concept.concept_id,
            feature_id=f_c,
            attempt=attempt,
        ):
            outcome = classify_avoid_continuation(
                prefix_text=prefix_row["prefix_text"],
                continuation_text=continuation,
                f_c=f_c,
                base_model=base_model,
                base_sae=base_sae,
                sae_layer=sae_layer,
                extraction_threshold=cfg.extraction_threshold,
                tokenizer_id=cfg.extraction_tokenizer_id,
                **_cluster_target_kwargs(cluster_target),
            )
        if outcome is AvoidContinuationOutcome.NO_TOKENS:
            record_counter(
                "stage1c.qc_empty_rejects",
                1,
                concept_id=concept.concept_id,
                attempt=attempt,
            )
            continue
        if outcome is AvoidContinuationOutcome.INACTIVE:
            record_counter(
                "stage1c.qc_accepts",
                1,
                concept_id=concept.concept_id,
                attempt=attempt,
            )
            record_counter(
                "stage1c.qc_attempts_to_accept",
                attempt + 1,
                concept_id=concept.concept_id,
                prefix_source_doc=prefix_row["prefix_source_doc"],
                outcome="accepted",
            )
            return _make_concept_avoiding_row(
                concept,
                prefix_row,
                continuation,
                attempt + 1,
                cfg,
                zero_activation_verified=True,
            )
        # NO_TOKENS and INACTIVE return/continue above, so ACTIVE is the only
        # remaining outcome. Fail loudly on any unmapped outcome (e.g. a future
        # enum member) rather than silently dropping the attempt uncounted.
        if outcome is not AvoidContinuationOutcome.ACTIVE:
            raise AxBenchBaseError(f"unhandled avoid-QC outcome: {outcome!r}")
        record_counter(
            "stage1c.qc_rejects",
            1,
            concept_id=concept.concept_id,
            attempt=attempt,
        )

    record_counter(
        "stage1c.qc_attempts_on_exhaustion",
        cfg.max_retries + 1,
        concept_id=concept.concept_id,
        prefix_source_doc=prefix_row["prefix_source_doc"],
        outcome="exhausted",
    )
    logger.debug(
        f"Concept {concept.concept_id} negative-synth exhausted all "
        f"{cfg.max_retries + 1} attempts. Last continuation: "
        f"{last_continuation[:80]!r}"
    )
    return None


def _synthesize_concept_negatives(
    cfg: AxBenchBaseConfig,
    concept: Concept,
    concept_prefixes: list[dict[str, Any]],
    base_model: Any,
    base_sae: Any,
    llm_client: SynthCompleter,
    target_model_meta: TargetModelMetadata,
    *,
    cluster_target: ClusterFeatureTarget | None = None,
) -> list[dict[str, Any]]:
    """Run the full Stage 1c loop for a single concept."""
    if not concept_prefixes:
        logger.warning(
            f"Concept {concept.concept_id} has no verified prefixes in Stage 0c "
            "output; skipping Stage 1c for this concept"
        )
        return []

    tokenizer = get_extraction_tokenizer(cfg.extraction_tokenizer_id)
    template = load_template("synth_continue_avoiding_concept.txt")
    sae_layer = target_model_meta.sae_layer

    rows: list[dict[str, Any]] = []
    for prefix_row in concept_prefixes:
        rows.extend(_copy_concept_rich_rows(concept, prefix_row, cfg))

        accepted_row = _synthesize_concept_avoiding_row(
            concept,
            prefix_row,
            cfg,
            base_model,
            base_sae,
            llm_client,
            tokenizer,
            template,
            sae_layer=sae_layer,
            **_cluster_target_kwargs(cluster_target),
        )
        if accepted_row is not None:
            rows.append(accepted_row)
            continue

        # QC exhausted. Dispatch per cfg.qc_fallback_on_exhaust.
        mode = cfg.qc_fallback_on_exhaust
        if mode == "error":
            raise AxBenchBaseError(
                f"Concept {concept.concept_id} (feature {concept.feature_index}): "
                f"concept_avoiding synthesis failed strict-zero QC after "
                f"{cfg.max_retries + 1} attempts on prefix "
                f"shard={prefix_row['prefix_source_shard']} "
                f"doc={prefix_row['prefix_source_doc']}."
            )
        if mode == "warn":
            logger.warning(
                f"Concept {concept.concept_id}: concept_avoiding QC exhausted "
                f"on prefix doc={prefix_row['prefix_source_doc']}; skipping row."
            )
            continue
        # mode == "best" (validated by validate_config).
        # Strict-zero QC has no delta to rank attempts by, so "best" has no
        # meaningful definition here. Document + fall through to the same
        # behavior as "warn" (log + leave an incomplete logical item for the
        # final pair filter to remove).
        logger.warning(
            f"Concept {concept.concept_id}: concept_avoiding QC exhausted "
            f"on prefix doc={prefix_row['prefix_source_doc']}; 'best' "
            "fallback has no meaningful definition for strict-zero QC, "
            "treating as 'warn' and skipping row."
        )

    return drop_unpaired_rich_rows(rows, concept.concept_id)


def _synth_max_concurrent(cfg: AxBenchBaseConfig) -> int:
    return max(1, int(cfg.synth.max_concurrent or 1))


