"""Stage 1c: negative-mode synthesis (spec §3.6).

For each verified prefix from Stage 0c (``negative_mode_prefixes.parquet``),
emit two kinds of rows:

1. ``concept_rich`` rows: one per passing verification continuation
   from Stage 0c (3-5 per prefix). These were generated by the target
   decoder-only base model and already passed the consistency check,
   so no re-verification or LLM call is needed. The percentile stored
   in ``qc_output_percentile`` comes from the Stage 0c
   ``verification_percentiles`` column. Per spec, these rows use
   ``category="positive"`` because they are the "desirable training
   sample for the concept-rich side" of negative-mode training.

2. ``concept_avoiding`` rows: one per verified prefix. Call the
   OpenRouter synth LLM with the ``synth_continue_avoiding_concept``
   template and an attempt-specific authenticated envelope/suffix-echo
   contract, then run strict-zero QC via the tri-state
   :func:`classify_avoid_continuation` (issue #518, mirroring
   positive-mode issue #513). Accept iff the outcome is ``INACTIVE`` —
   the concept feature does NOT fire above ``cfg.extraction_threshold``
   on any continuation token. An empty/whitespace provider continuation
   fails the protocol; a parsed continuation that adds no tokens beyond the
   prefix (``NO_TOKENS``) fails QC. Neither is a strict-zero PASS, and both
   are retried under their separate counters. Resample immediately up to
   ``cfg.max_retries`` additional content attempts. HTTP failures
   independently use ``cfg.synth.transport_max_retries`` with exponential
   backoff. On content exhaustion, dispatch per
   ``cfg.qc_fallback_on_exhaust``:

   - ``"error"`` (default): raise ``AxBenchBaseError``.
   - ``"warn"``: record an incomplete logical item. The final pair filter
     publishes neither the missing ``concept_avoiding`` row nor the copied
     ``concept_rich`` rows from that prefix.
   - ``"best"``: strict-zero QC has no delta to rank attempts by, so
     there is no meaningful "best" attempt. We document this and fall
     through to the same behavior as ``"warn"`` (log + skip).

Output: ``synth_training_negative.parquet`` with the 15 Stage-1b
columns plus 4 negative-mode extras:

- ``prefix_source_shard``
- ``prefix_source_doc``
- ``prefix_source_seg_idx``
- ``qc_zero_activation_verified``

When ``cfg.synth.max_concurrent > 1``, concept-avoiding LLM calls are
issued through one bounded request-chain pool spanning all concept/prefix
pairs. A pair's attempts remain sequential and lazy, while different pairs
progress independently without attempt-wave barriers. Worker threads perform
only provider completion; parsing, strict-zero QC, fallback handling, and
canonical final row assembly remain on the caller thread.
"""

