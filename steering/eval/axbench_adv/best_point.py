def write_counter_best_points(aggregate: pa.Table, output_dir: Path) -> Path:
    """Select magnitude by GEPA mean fitness, ties to lower alpha."""
    rows = aggregate.to_pylist()
    selected = {}
    for method in dict.fromkeys(row["method"] for row in rows):
        candidates = sorted(
            (row for row in rows if row["method"] == method), key=lambda row: row["magnitude"]
        )
        best = max(candidates, key=lambda row: row["mean_fitness"])
        selected[method] = best
    path = output_dir / "best_points.json"
    atomic_write_text(json.dumps(selected, indent=2, sort_keys=True, allow_nan=False) + "\n", path)
    return path
