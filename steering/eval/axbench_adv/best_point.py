"""Select each attacked method's factor from the historical main evaluation.

Selection preserves the closed-PR #1385 oracle: macro-average concept and
fluency ratings across concepts, take their two-way zero-bottom harmonic mean,
and select the first factor on a tie. Historical generations are used only for
this choice; the plotted control is regenerated by the new worker.
"""

from __future__ import annotations

import csv
import io
import json
import math
from collections.abc import Mapping, Sequence
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import pyarrow as pa

from nanochat.atomic_io import atomic_write_text
from steering._common.strict_json import (
    reject_nonstandard_json_constant,
    strict_json_object,
)
from steering.eval.axbench_adv.errors import AxBenchAdvError
from steering.eval.axbench_adv.method_grid import ALL_METHOD_FACTORS
from steering.eval.axbench_adv.types import METHODS
from steering.eval.axbench_base.aggregation import hmean

_EVALUATOR_KEY = "LMJudgeEvaluator"
_CONCEPT_FIELD = "relevance_concept_ratings"
_FLUENCY_FIELD = "fluency_ratings"


@dataclass(frozen=True)
class BestPoint:
    """The selected factor and its macro concept/fluency scores."""

    method: str
    factor: float
    concept_score: float
    fluency_score: float
    hm2: float


def load_steering_entries(
    steering_jsonl: Path,
    *,
    expected_concept_ids: Sequence[int] | None = None,
) -> list[dict[str, Any]]:
    """Load an ascending, exactly-one-entry-per-concept JSONL."""

    path = Path(steering_jsonl)
    if not path.is_file():
        raise AxBenchAdvError(f"main evaluation steering.jsonl not found: {path}")
    entries: list[dict[str, Any]] = []
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError) as exc:
        raise AxBenchAdvError(f"invalid JSON in {path}: file is not valid UTF-8") from exc
    for line_number, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        try:
            entry = json.loads(
                line,
                parse_constant=reject_nonstandard_json_constant,
                object_pairs_hook=strict_json_object,
            )
        except (json.JSONDecodeError, ValueError) as exc:
            raise AxBenchAdvError(f"invalid JSON in {path} at line {line_number}: {exc}") from exc
        if not isinstance(entry, Mapping) or set(entry) != {"concept_id", "results"}:
            raise AxBenchAdvError(
                f"steering.jsonl entry at line {line_number} must contain only "
                "concept_id and results"
            )
        entries.append(dict(entry))
    if not entries:
        raise AxBenchAdvError(f"steering.jsonl is empty: {path}")
    _require_concept_order(entries, expected_concept_ids=expected_concept_ids)
    return entries


def _require_concept_order(
    entries: Sequence[Mapping[str, Any]],
    *,
    expected_concept_ids: Sequence[int] | None = None,
) -> None:
    """Reject missing, duplicate, reordered, or Boolean concept identities."""

    concept_ids = [entry["concept_id"] for entry in entries]
    expected = (
        list(range(len(entries))) if expected_concept_ids is None else list(expected_concept_ids)
    )
    if (
        not expected
        or any(type(value) is not int or value < 0 for value in expected)
        or expected != sorted(set(expected))
    ):
        raise AxBenchAdvError("expected_concept_ids must be nonempty, nonnegative, unique, and ascending")
    if any(type(value) is not int for value in concept_ids) or concept_ids != expected:
        raise AxBenchAdvError(
            "steering.jsonl must contain each concept exactly once in ascending order; "
            f"observed concept_ids={concept_ids}"
        )


def _as_entries(
    source: Path | Sequence[Mapping[str, Any]],
    *,
    expected_concept_ids: Sequence[int] | None = None,
) -> list[dict[str, Any]]:
    if isinstance(source, (str, Path)):
        return load_steering_entries(
            Path(source),
            expected_concept_ids=expected_concept_ids,
        )
    entries: list[dict[str, Any]] = []
    for entry in source:
        if not isinstance(entry, Mapping) or "concept_id" not in entry:
            raise AxBenchAdvError("steering entries must each carry a concept_id")
        entries.append(dict(entry))
    if not entries:
        raise AxBenchAdvError("steering entries must not be empty")
    _require_concept_order(entries, expected_concept_ids=expected_concept_ids)
    return entries


def _requested_factor(
    method: str,
    factor: Any,
    *,
    method_factors: Mapping[str, Sequence[float]] = ALL_METHOD_FACTORS,
) -> float:
    if method not in method_factors:
        raise AxBenchAdvError(f"unknown attacked method: {method!r}")
    if isinstance(factor, bool) or not isinstance(factor, (int, float)):
        raise AxBenchAdvError("requested factor must be numeric")
    numeric = float(factor)
    if not math.isfinite(numeric):
        raise AxBenchAdvError("requested factor must be finite")
    if numeric not in tuple(float(value) for value in method_factors[method]):
        raise AxBenchAdvError(
            f"factor {factor} is not on {method}'s declared grid {method_factors[method]}"
        )
    return numeric


def _method_block(entry: Mapping[str, Any], method: str) -> Mapping[str, Any]:
    results = entry.get("results")
    if not isinstance(results, Mapping):
        raise AxBenchAdvError("steering.jsonl entry has no results mapping")
    evaluator = results.get(_EVALUATOR_KEY)
    if not isinstance(evaluator, Mapping):
        raise AxBenchAdvError(f"steering.jsonl entry has no {_EVALUATOR_KEY} results")
    block = evaluator.get(method)
    if not isinstance(block, Mapping):
        raise AxBenchAdvError(f"steering.jsonl entry has no {method!r} judge block")
    return block


def _require_list(value: Any, method: str, name: str) -> list[Any]:
    if not isinstance(value, Sequence) or isinstance(value, (str, bytes)):
        raise AxBenchAdvError(f"{method}.{name} must be a list in steering.jsonl")
    return list(value)


def _rating(value: Any, *, method: str, field: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise AxBenchAdvError(f"{method}.{field} contains a nonnumeric rating")
    rating = float(value)
    if not math.isfinite(rating) or not 0.0 <= rating <= 2.0:
        raise AxBenchAdvError(f"{method}.{field} rating {rating!r} is outside [0, 2]")
    return rating


def _aligned_ratings(
    block: Mapping[str, Any], method: str, factor: float, rating_fields: tuple[str, ...]
) -> tuple[float, ...]:
    factors = _require_list(block.get("factor"), method, "factor")
    ratings = [_require_list(block.get(field), method, field) for field in rating_fields]
    if any(len(values) != len(factors) for values in ratings):
        raise AxBenchAdvError(f"{method} factor/rating lists have mismatched lengths")
    numeric_factors: list[float] = []
    for value in factors:
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise AxBenchAdvError(f"{method}.factor contains a nonnumeric value")
        numeric = float(value)
        if not math.isfinite(numeric):
            raise AxBenchAdvError(f"{method}.factor contains a nonfinite value")
        numeric_factors.append(numeric)
    matches = [index for index, value in enumerate(numeric_factors) if value == float(factor)]
    if len(matches) != 1:
        raise AxBenchAdvError(
            f"{method} judge block must list factor {factor} exactly once, "
            f"observed {len(matches)} in {factors!r}"
        )
    index = matches[0]
    return tuple(
        _rating(values[index], method=method, field=field)
        for field, values in zip(rating_fields, ratings, strict=True)
    )


def per_concept_ratings(
    source: Path | Sequence[Mapping[str, Any]],
    method: str,
    factor: float,
    *,
    expected_concept_ids: Sequence[int] | None = None,
    rating_fields: tuple[str, ...] = (_CONCEPT_FIELD, _FLUENCY_FIELD),
    method_factors: Mapping[str, Sequence[float]] = ALL_METHOD_FACTORS,
) -> tuple[list[float], ...]:
    """Return requested ratings in concept order; default to concept and fluency."""

    numeric_factor = _requested_factor(method, factor, method_factors=method_factors)
    entries = _as_entries(source, expected_concept_ids=expected_concept_ids)
    values: tuple[list[float], ...] = tuple([] for _ in rating_fields)
    for entry in entries:
        ratings = _aligned_ratings(
            _method_block(entry, method), method, numeric_factor, rating_fields
        )
        for column, rating in zip(values, ratings, strict=True):
            column.append(rating)
    return values


def concept_fluency_point(
    source: Path | Sequence[Mapping[str, Any]],
    method: str,
    factor: float,
    *,
    method_factors: Mapping[str, Sequence[float]] = ALL_METHOD_FACTORS,
) -> tuple[float, float]:
    """Return macro-averaged concept and fluency ratings at one factor."""

    concept_values, fluency_values = per_concept_ratings(
        source,
        method,
        factor,
        method_factors=method_factors,
    )
    return (
        sum(concept_values) / len(concept_values),
        sum(fluency_values) / len(fluency_values),
    )


def select_best_point(
    source: Path | Sequence[Mapping[str, Any]],
    method: str,
    *,
    method_factors: Mapping[str, Sequence[float]] = ALL_METHOD_FACTORS,
) -> BestPoint:
    """Select the first factor maximizing macro two-way harmonic mean."""

    entries = _as_entries(source)
    if method not in method_factors:
        raise AxBenchAdvError(f"unknown attacked method: {method!r}")
    return max(
        (
            point_at_factor(
                entries,
                method,
                float(factor),
                method_factors=method_factors,
            )
            for factor in method_factors[method]
        ),
        key=lambda point: point.hm2,
    )


def point_at_factor(
    source: Path | Sequence[Mapping[str, Any]],
    method: str,
    factor: float,
    *,
    method_factors: Mapping[str, Sequence[float]] = ALL_METHOD_FACTORS,
) -> BestPoint:
    """Return the exact declared point selected by an explicit factor override."""

    concept_score, fluency_score = concept_fluency_point(
        source,
        method,
        factor,
        method_factors=method_factors,
    )
    return BestPoint(
        method=method,
        factor=_requested_factor(method, factor, method_factors=method_factors),
        concept_score=concept_score,
        fluency_score=fluency_score,
        hm2=hmean(concept_score, fluency_score),
    )


def select_best_points(
    source: Path | Sequence[Mapping[str, Any]],
    methods: Sequence[str] = METHODS,
    *,
    method_factors: Mapping[str, Sequence[float]] = ALL_METHOD_FACTORS,
) -> dict[str, BestPoint]:
    """Select factors for each requested method in caller-specified order."""

    entries = _as_entries(source)
    requested = tuple(methods)
    if not requested or len(set(requested)) != len(requested):
        raise AxBenchAdvError("methods must be nonempty and unique")
    return {
        method: select_best_point(entries, method, method_factors=method_factors)
        for method in requested
    }


def write_best_points(best_points: Mapping[str, BestPoint], output_dir: Path) -> tuple[Path, Path]:
    """Write the factor-selection evidence as JSON and CSV."""

    if not best_points:
        raise AxBenchAdvError("best_points must not be empty")
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    ordered = {method: best_points[method] for method in sorted(best_points)}
    json_path = output_dir / "best_points.json"
    atomic_write_text(
        json.dumps(
            {method: asdict(point) for method, point in ordered.items()},
            indent=2,
            sort_keys=True,
            allow_nan=False,
        )
        + "\n",
        json_path,
    )
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["method", "factor", "concept_score", "fluency_score", "hm2"])
    for method, point in ordered.items():
        writer.writerow([method, point.factor, point.concept_score, point.fluency_score, point.hm2])
    csv_path = output_dir / "best_points.csv"
    atomic_write_text(buffer.getvalue(), csv_path)
    return json_path, csv_path


